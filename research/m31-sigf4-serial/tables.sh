#!/usr/bin/env bash
# Regenerates tables.md: each change against its parent, then the stack against the freeze.
set -euo pipefail
here="$(dirname "$0")"
{
  echo "# #903 tables"
  echo
  echo "Generated by \`tables.sh\` (\`summarize.py\`) from \`campaign1.jsonl.gz\`, \`heldout.jsonl.gz\` and \`stages.jsonl.gz\`."
  for records in campaign1 heldout stages; do
    for pair in "base interreduce" "interreduce bookkeeping" "bookkeeping symbolic" "base symbolic"; do
      read -r base head <<<"$pair"
      echo
      echo "## $records: $head / $base"
      echo
      python3 "$here/summarize.py" --base "$base" --head "$head" "$here/$records.jsonl.gz"
    done
  done
} > "$here/tables.md"
