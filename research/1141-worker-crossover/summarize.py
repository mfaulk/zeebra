#!/usr/bin/env python3
"""Tables for #978's held-out check from `held.jsonl` (`run.py`): per row and worker count, median
process wall per engine, sigf4 / f4 with a 95% bootstrap CI, the entry route, and the
pre-declared verdict (issue #978, comment 7149570887)."""
import gzip
import json
import random
import statistics
import sys
from collections import defaultdict

TOLERANCE = 0.05


def ci(a, b, n=4000, seed=978):
    rng = random.Random(seed)
    ratios = sorted(statistics.median(rng.choices(a, k=len(a))) / statistics.median(rng.choices(b, k=len(b)))
                    for _ in range(n))
    return ratios[int(0.025 * n)], ratios[int(0.975 * n) - 1]


def main(path):
    walls, routes, bases, failures = defaultdict(list), defaultdict(set), defaultdict(set), []
    for line in (gzip.open(path, 'rt') if path.endswith('.gz') else open(path)):
        r = json.loads(line)
        key = (r['row'], r['workers'])
        rep = r['report'] or {}
        if r['returncode'] != 0 or rep.get('status') != 'complete':
            failures.append((r['row'], r['engine'], r['workers'], r['returncode']))
            continue
        walls[key + (r['engine'],)].append(r['process_wall_ns'] / 1e6)
        bases[r['row']].add(rep.get('basis_m33'))
        if r['engine'] == 'entry':
            routes[key].add((rep.get('statistics') or {}).get('route'))
    rows = sorted({k[0] for k in walls})
    print('# #978 held-out check of the narrowed WorkerCrossover band\n')
    print('**Measured at:** `e3a25264` (PR #1115 rebased onto `main` `48778879`, tag '
          '`measured/978-held-out`), bench host, CCDs 1-2 reserved; see `provenance.txt`. Generated by '
          '`summarize.py held.jsonl.gz`. Medians of 9 fresh processes, process wall.\n')
    print('| row | witness | w | f4 ms | sigf4 ms | entry ms | sigf4 / f4 [95% CI] | entry route | verdict |')
    print('|---|---|---:|---:|---:|---:|---|---|---|')
    agree_all = True
    for row in rows:
        for w in (4, 8, 16):
            f4, sig, entry = (walls[(row, w, e)] for e in ('f4', 'sigf4', 'entry'))
            if not (f4 and sig and entry):
                continue
            ratio = statistics.median(sig) / statistics.median(f4)
            lo, hi = ci(sig, f4)
            route = ', '.join(sorted(map(str, routes[(row, w)])))
            witness = 'WorkerCrossover' in route
            agrees = ratio >= 1 - TOLERANCE if witness else ratio <= 1 + TOLERANCE
            expected = 'Shipping(WorkerCrossover)' if witness else 'Signature'
            agrees = agrees and routes[(row, w)] == {expected}
            agree_all &= agrees
            print(f'| {row} | {"yes" if witness else "no"} | {w} | {statistics.median(f4):.1f} '
                  f'| {statistics.median(sig):.1f} | {statistics.median(entry):.1f} '
                  f'| {ratio:.3f} [{lo:.3f}, {hi:.3f}] | {route} | {"agrees" if agrees else "**disagrees**"} |')
    print()
    print(f'Bases: {sum(len(v) == 1 for v in bases.values())} of {len(bases)} rows give one `basis_m33` '
          'digest across all engines and worker counts.')
    print(f'Failed children: {len(failures)} {failures[:5]}')
    print(f'Verdict: {"CONFIRMED" if agree_all and not failures else "NOT CONFIRMED"}')


if __name__ == '__main__':
    main(sys.argv[1])
