#!/usr/bin/env python3
"""Tables for #1141's held-out check from `probe.jsonl` and `held.jsonl` (`run.py`): per row and
worker count, median process wall per forced engine, sigf4 / f4 with a 95% bootstrap CI, the
routes of the candidate and incumbent rules, and the verdict pre-declared on #1141 (issue comment
7169381783).

    summarize.py probe.jsonl[.gz] held.jsonl[.gz] [commit]
"""
import gzip
import json
import random
import statistics
import sys
from collections import defaultdict

TOLERANCE = 0.05
FLOOR_MS, CEILING_MS = 20, 30_000
TERMS_BELOW, WIDE_WORKERS = 114, 16
CONTROLS = {'gf32003/mq-random-10-s10', 'm31/mq-random-10-s10', 'gf32003/katsura-10',
            'm31/katsura-10'}


def records(path):
    for line in (gzip.open(path, 'rt') if path.endswith('.gz') else open(path)):
        yield json.loads(line)


def ci(a, b, n=4000, seed=1141):
    rng = random.Random(seed)
    ratios = sorted(statistics.median(rng.choices(a, k=len(a))) / statistics.median(rng.choices(b, k=len(b)))
                    for _ in range(n))
    return ratios[int(0.025 * n)], ratios[int(0.975 * n) - 1]


def in_band(f):
    return f['variables'] == 10 and f['max_degree'] == 2 and f['witness'] is not None


def incumbent(f, w):
    return 'F4' if in_band(f) and w >= 4 else 'sig'


def candidate(f, w):
    return 'F4' if in_band(f) and (w >= WIDE_WORKERS or (w >= 4 and f['terms'] < TERMS_BELOW)) else 'sig'


def agrees(pick, ratio):
    return ratio >= 1 - TOLERANCE if pick == 'F4' else ratio <= 1 + TOLERANCE


def main(probe_path, held_path, commit='<commit>'):
    feats, dropped = {}, []
    for r in records(probe_path):
        feats[r['row']] = r['features']
        walls = [r[e]['wall_ns'] / 1e6 for e in ('f4', 'sigf4')]
        if any(r[e]['rc'] != 0 for e in ('f4', 'sigf4')):
            dropped.append((r['row'], 'probe failed'))
        elif min(walls) < FLOOR_MS:
            dropped.append((r['row'], f'floor: faster engine {min(walls):.1f} ms at 16 w'))
        elif max(walls) > CEILING_MS:
            dropped.append((r['row'], f'ceiling: slower engine {max(walls) / 1e3:.1f} s at 16 w'))
    walls, bases, failures = defaultdict(list), defaultdict(set), []
    for r in records(held_path):
        rep = r['report'] or {}
        if r['returncode'] != 0 or rep.get('status') != 'complete':
            failures.append((r['row'], r['engine'], r['workers'], r['returncode']))
            continue
        walls[(r['row'], r['workers'], r['engine'])].append(r['process_wall_ns'] / 1e6)
        bases[r['row']].add(rep.get('basis_m33'))
    rows = sorted({k[0] for k in walls}, key=lambda r: (r in CONTROLS, r.split('/')[1], r))
    print('# #1141 held-out check of the term-count WorkerCrossover rule\n')
    print(f'**Measured at:** `{commit}`, bench host, CCDs 1-2 reserved; see `provenance.txt`. Generated by '
          '`summarize.py probe.jsonl.gz held.jsonl.gz`. Medians of 9 fresh processes, process wall. '
          f'Candidate: F4 iff in band and (w >= {WIDE_WORKERS} or (w >= 4 and terms < {TERMS_BELOW})); '
          'incumbent (#1115): F4 iff in band and w >= 4. In band = 10 variables, degree 2, witness.\n')
    print('| row | terms | in band | w | f4 ms | sigf4 ms | sigf4 / f4 [95% CI] | candidate | incumbent |')
    print('|---|---:|---|---:|---:|---:|---|---|---|')
    scored = cand_ok = inc_ok = 0
    heavy = []
    for row in rows:
        f = feats[row]
        for w in (4, 8, 16):
            f4, sig = walls[(row, w, 'f4')], walls[(row, w, 'sigf4')]
            if not (f4 and sig):
                continue
            ratio = statistics.median(sig) / statistics.median(f4)
            lo, hi = ci(sig, f4)
            c, i = candidate(f, w), incumbent(f, w)
            ca, ia = agrees(c, ratio), agrees(i, ratio)
            score = in_band(f) and row not in CONTROLS
            if score:
                scored += 1
                cand_ok += ca
                inc_ok += ia
                if (c == 'sig' and lo > 1.25) or (c == 'F4' and hi < 0.80):
                    heavy.append((row, w, round(ratio, 3)))
            mark = lambda pick, ok: f'{pick} {"ok" if ok else "**no**"}'
            print(f'| {row}{"" if score else " (control)" if row in CONTROLS else " (unscored)"} '
                  f'| {f["terms"]} | {"yes" if in_band(f) else "no"} | {w} '
                  f'| {statistics.median(f4):.1f} | {statistics.median(sig):.1f} '
                  f'| {ratio:.3f} [{lo:.3f}, {hi:.3f}] | {mark(c, ca)} | {mark(i, ia)} |')
    print()
    print(f'Dropped by the probe: {len(dropped)} {dropped}')
    print(f'Bases: {sum(len(v) == 1 for v in bases.values())} of {len(bases)} rows give one `basis_m33` '
          'digest across both engines and worker counts.')
    print(f'Failed children: {len(failures)} {failures[:5]}')
    frac = cand_ok / scored if scored else 0
    print(f'Scored cells: {scored}. Candidate agrees on {cand_ok} ({frac:.0%}), incumbent on {inc_ok}.')
    print(f'Candidate cells slower by more than 1.25x (CI bound): {heavy}')
    confirmed = scored and frac >= 0.90 and cand_ok > inc_ok and not heavy and not failures
    print(f'Verdict: {"CONFIRMED" if confirmed else "NOT CONFIRMED"}')


if __name__ == '__main__':
    main(*sys.argv[1:])
