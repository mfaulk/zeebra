#!/usr/bin/env python3
"""#1191 cost model: `tables.md` from the census records and #1039's committed stage medians.

    model.py [--census census.jsonl] [--stages ../1039-wiedemann-lex/tables.md] > tables.md

Counts are field operations (a unit column is one move), with every constant and logarithm of the
polynomial-matrix route dropped, so its column is a floor and the ratio beside it a ceiling on what
the route could gain.
"""
import argparse
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Berthomieu-Neiger-Safey El Din, ISSAC 2022, Table 2 (seconds, one thread, 30-bit prime, their
# host): (D, t) -> (F4, F4 tracer, msolve Wiedemann, NTL block Wiedemann, PML Hermite form).
PAPER = {
    (2048, 462): (11.6, 1.1, 1.2, 1.7, 0.8),
    (4096, 924): (115.9, 8.3, 6.5, 14.5, 5.3),
    (8192, 1716): (970, 62, 103.6, 110, 34.8),
    (16384, 3432): (7921, 460, 1011, 880, 240),
    (32768, 6435): (61381, 3193, 7844, 6691, 1665),
    (65536, 12870): (482515, 24523, 58744, 52709, 11359),
    (6561, 1107): (122.6, 12.8, 23.6, 44.7, 15.1),
    (19683, 3139): (3552.7, 361, 1302, 1163, 314),
    (59049, 8953): (95052, 8664, 34844, 29974, 6709),
    (4096, 580): (9.9, 2.2, 4, 8.8, 3.5),
    (16384, 2128): (876, 128, 575, 545, 157),
    (65536, 8092): (57237, 6977, 36454, 33452, 7231),
}
GATE = 1.5


def stage_medians(path):
    """#1039's `zb-wiedemann` stage medians (ms) by row, from its generated tables."""
    out = {}
    for line in Path(path).read_text().splitlines():
        cells = [c.strip() for c in line.split('|')]
        if len(cells) < 5 or cells[2] != 'zb-wiedemann':
            continue
        stages = {k: float(v.replace(',', '')) for k, v in
                  re.findall(r'(F4|operators|sequence|reconstruction|certificate) ([\d,.]+)', cells[4])}
        out[cells[1]] = dict(wall=float(cells[3].replace(',', '')), **stages)
    return out


def fmt(x):
    if x >= 1e5:
        return f'{x:.2e}'
    return f'{x:,.0f}' if x >= 100 else f'{x:.2f}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--census', default=str(HERE / 'census.jsonl'))
    ap.add_argument('--stages', default=str(HERE.parent / '1039-wiedemann-lex/tables.md'))
    args = ap.parse_args()
    rows = [json.loads(line) for line in open(args.census)]
    rows = [r for r in rows if r.get('arm') == 'probe' and r.get('status') == 'complete']
    stages = stage_medians(args.stages)

    print('# #1191 tables (generated by `model.py`)\n')
    print('## 1. Module census\n')
    print('| Row | N | D | t | leaders on y | stable | other variables standard | D / t '
          '| longest chain | last operator entries z | z / (t D) |')
    print('|---|---|---|---|---|---|---|---|---|---|---|')
    for r in rows:
        d, t, z = r['dimension'], r['module_rank'], r['last_stored_entries']
        print(f"| `{r['row']}` | {r['variables']} | {d:,} | {t:,} | {r['last_variable_leaders']:,} "
              f"| {'yes' if r['stable'] else 'no'} "
              f"| {'yes' if r['other_variables_standard'] else 'no'} | {d / t:.1f} "
              f"| {r['max_column_degree']} | {z:,} | {z / (t * d):.2f} |")

    print('\n## 2. Operation counts\n')
    print('Scalar route, with `u` the unit columns: sequence `2 D (z + u)`, certificate '
          '`D (z + u) + (N - 1) D^2`. Polynomial-matrix floor: `t^2 D`.\n')
    print('| Row | sequence | certificate | polynomial-matrix floor | scalar / floor (ceiling on gain) '
          '| paper, same (D, t): Wiedemann / Hermite |')
    print('|---|---|---|---|---|---|')
    for r in rows:
        d, t, n = r['dimension'], r['module_rank'], r['variables']
        z = r['last_stored_entries'] + r['last_standard_columns']
        seq, cert, floor = 2 * d * z, d * z + (n - 1) * d * d, t * t * d
        paper = PAPER.get((d, t))
        measured = f'{paper[2] / paper[4]:.2f}' if paper else '-'
        print(f"| `{r['row']}` | {fmt(seq)} | {fmt(cert)} | {fmt(floor)} "
              f"| {(seq + cert) / floor:.2f} | {measured} |")

    print('\n## 3. Row-level bound on rows with a committed stage split\n')
    print(f'Stage medians (ms) are #1039\'s `zb-wiedemann` arm. "Needed" is the gain on sequence + '
          f'reconstruction + certificate that makes the whole row {GATE}x faster once operator '
          f'construction is already gone.\n')
    print('| Row | wall | F4 | operators | sequence + reconstruction + certificate '
          '| wall without operators | row gain from that alone | row gain if the rest were free '
          '| needed |')
    print('|---|---|---|---|---|---|---|---|---|')
    for r in rows:
        s = stages.get(r['row'])
        if not s:
            continue
        scalar = s['sequence'] + s['reconstruction'] + s['certificate']
        without = s['wall'] - s['operators']
        fixed = without - scalar
        target = without / GATE - fixed
        needed = f'{scalar / target:.2f}' if target > 0 else 'unreachable'
        print(f"| `{r['row']}` | {fmt(s['wall'])} | {fmt(s['F4'])} | {fmt(s['operators'])} "
              f"| {fmt(scalar)} | {fmt(without)} | {s['wall'] / without:.2f} "
              f"| {without / max(fixed, 1e-9):.2f} | {needed} |")


if __name__ == '__main__':
    main()
