#!/usr/bin/env python3
"""tables.md for #1198 from runs.jsonl.gz: python3 summarize.py > tables.md

Every figure is a count or a byte total derived from counts; none is a timing.
"""
import gzip
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))

# M4GB's counters at the same shape, from docs/research/m4gb-m5gb-reference.md §9 (planted rows;
# they depend only on (n, m)): peak basis, peak store, peak dense width.
M4GB = {
    (14, 25): (479, 11213, 720),
    (14, 28): (140, 2513, 547),
    (16, 29): (655, 19197, 1321),
    (16, 32): (807, 19884, 1080),
}


def load():
    with gzip.open(os.path.join(HERE, "runs.jsonl.gz"), "rt") as f:
        runs = [json.loads(line) for line in f if line.strip()]
    for r in runs:
        r["shape"] = shape(r["row"])
        if r.get("lane"):
            r["row"] += " +lane"
    return runs


def mib(b):
    return f"{b / 2**20:,.1f}"


def ratio(a, b):
    return f"{a / b:.2f}" if b else "—"


def shape(row):
    m = re.match(r"dmq-n(\d+)-m(\d+)-", row)
    return (int(m.group(1)), int(m.group(2))) if m else None


def dense_bytes(b, cells, coefficient):
    """A dense batch store: the cells, a column-to-slot map and one accumulator."""
    return cells * coefficient + 4 * b["columns"] + 8 * b["irreducible_before"]


def main():
    runs = load()
    out = ["# #1198: irreducible-indexed dense tail store, counted", ""]
    out += [
        "Generated by `summarize.py` from `runs.jsonl.gz`. One signature-engine run per row at one",
        "worker with `--tail-store`. Counts and byte totals only.",
        "",
        "## 1. Columns against irreducible monomials",
        "",
        "`peak columns` is the widest batch; `irreducible` is the columns of that batch no basis",
        "lead divides when it is built; `peak irreducible` is the largest such count over the run.",
        "",
        "| Row | status | batches | peak columns | irreducible there | share | peak irreducible | M4GB peak dense width |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in runs:
        ts = (r.get("tail_store") or {}).get("batches") or []
        if not ts:
            out.append(f"| `{r['row']}` | {r['status']} | — | — | — | — | — | — |")
            continue
        wide = max(ts, key=lambda b: b["columns"])
        peak_irr = max(b["irreducible_before"] for b in ts)
        m4 = M4GB.get(r["shape"])
        out.append(
            f"| `{r['row']}` | {r['status'].split(':')[0]} | {len(ts)} | {wide['columns']:,} | "
            f"{wide['irreducible_before']:,} | {wide['irreducible_before'] / wide['columns']:.3f} | "
            f"{peak_irr:,} | {m4[2] if m4 else '—'} |"
        )

    out += [
        "",
        "## 2. Bytes: the batch as the engine holds it against a dense store",
        "",
        "Per row, at the batch where each quantity peaks. `built` is the sparse entries of targets",
        "and reducers as built times the entry size; `engine live` is the engine's own live-byte",
        "peak for one batch (rows, reduced rows, pivot maps, workspaces). `dense` is one vector per",
        "row over the batch's irreducible columns at the field's coefficient size, plus a",
        "column-to-slot map and one accumulator; `below lead` keeps only the cells below each row's",
        "lead. `gain` is `engine live / dense`: the issue's gate is 2.0 on the dense rows.",
        "",
        "| Row | entry / coefficient bytes | built MiB | engine live MiB | dense MiB | below lead MiB | gain | gain below lead | fill of dense cells |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    gains = {}
    for r in runs:
        t = r.get("tail_store") or {}
        ts = t.get("batches") or []
        if not ts:
            continue
        e, c = t["entry_bytes"], t["coefficient_bytes"]
        built = max((b["target_entries"] + b["reducer_entries"]) * e for b in ts)
        live = max(b["live_peak_bytes"] for b in ts)
        dense = max(dense_bytes(b, b["dense_cells"], c) for b in ts)
        below = max(dense_bytes(b, b["dense_cells_below_lead"], c) for b in ts)
        wide = max(ts, key=lambda b: b["dense_cells"])
        fill = (wide["target_entries"] + wide["reducer_entries"]) / max(wide["dense_cells"], 1)
        gains[r["row"]] = (live / dense, live / below)
        out.append(
            f"| `{r['row']}` | {e} / {c} | {mib(built)} | {mib(live)} | {mib(dense)} | {mib(below)} | "
            f"**{ratio(live, dense)}** | {ratio(live, below)} | {fill:.2f} |"
        )

    out += [
        "",
        "`fill` is built entries over dense cells at the batch with the most cells. Above 1 the",
        "rows as built hold more entries than the dense store has cells, because built rows also",
        "carry entries at reducible columns.",
        "",
        "## 3. A run-wide store of multiples",
        "",
        "M4GB keeps its tail-reduced multiples across rounds. `multiples` is the distinct",
        "`(element, multiplier)` reducer rows the run built; `rebuilt` is the share of reducer rows",
        "that repeat an earlier batch's multiple. `store` charges every distinct multiple one dense",
        "vector at the run's peak irreducible width, never evicted.",
        "",
        "| Row | reducer rows | distinct multiples | rebuilt | M4GB peak store | store MiB | engine live MiB | basis elements | M4GB peak basis |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in runs:
        t = r.get("tail_store") or {}
        ts = t.get("batches") or []
        if not ts:
            continue
        c = t["coefficient_bytes"]
        rows = sum(b["reducers"] for b in ts)
        multiples = ts[-1]["multiples"]
        width = max(b["irreducible_before"] for b in ts)
        live = max(b["live_peak_bytes"] for b in ts)
        m4 = M4GB.get(r["shape"])
        out.append(
            f"| `{r['row']}` | {rows:,} | {multiples:,} | {1 - multiples / max(rows, 1):.2f} | "
            f"{f'{m4[1]:,}' if m4 else '—'} | {mib(multiples * width * c)} | {mib(live)} | "
            f"{ts[-1]['basis_elements']:,} | {m4[0] if m4 else '—'} |"
        )

    out += [
        "",
        "## 4. The basis, and what the tail-reduced invariant costs",
        "",
        "`born reducible` is the share of tail terms some lead already divided when the element was",
        "added (the engine clears only admissible pivots). `invalidated` is the share of the",
        "remaining tail terms a later lead made reducible, each counted once, without the fill-in a",
        "re-reduction would add: a lower bound. `touches / lead` is the stored elements a new lead",
        "invalidates, averaged over the leads that invalidate any.",
        "",
        "`before the last adding batch` is the same share over the batches before the last one",
        "that adds an element, against the tail terms stored by then: on a planted dense row the",
        "last adding batch is the collapse to linear leads, after which no stored tail is read.",
        "",
        "| Row | basis elements | tail terms | born reducible | invalidated | before the last adding batch | leads that invalidate | touches / lead | basis sparse MiB | basis dense MiB |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in runs:
        t = r.get("tail_store") or {}
        ts = t.get("batches") or []
        if not ts:
            continue
        last = ts[-1]
        elements = last["basis_elements"]
        tails = last["basis_terms"] - elements
        born = sum(b["element_reducible_entries"] for b in ts)
        invalidated = sum(b["invalidated_terms"] for b in ts)
        leads = sum(b["invalidating_leads"] for b in ts)
        touches = sum(b["invalidated_elements"] for b in ts)
        width = max(b["basis_irreducible_monomials"] for b in ts)
        adding = max(i for i, b in enumerate(ts) if b["elements"])
        early = sum(b["invalidated_terms"] for b in ts[:adding])
        stored = ts[adding - 1]["basis_terms"] - ts[adding - 1]["basis_elements"] if adding else 0
        sparse = last["basis_terms"] * (t["term_bytes"] + 8)
        dense = elements * width * t["coefficient_bytes"]
        out.append(
            f"| `{r['row']}` | {elements:,} | {tails:,} | {born / max(tails, 1):.3f} | "
            f"{invalidated / max(tails - born, 1):.3f} | {early / max(stored, 1):.3f} | "
            f"{leads:,} of {elements:,} | "
            f"{touches / max(leads, 1):,.1f} | {mib(sparse)} | {mib(dense)} |"
        )

    out += [
        "",
        "`basis sparse` charges each term its monomial, coefficient and hash, as the engine stores",
        "it; `basis dense` is one vector per element over the peak count of distinct irreducible",
        "tail monomials.",
        "",
        "## 5. Per batch",
        "",
    ]
    for r in runs:
        t = r.get("tail_store") or {}
        ts = t.get("batches") or []
        if not ts:
            continue
        e, c = t["entry_bytes"], t["coefficient_bytes"]
        out += [
            f"### `{r['row']}`",
            "",
            f"input `{r['input_digest'][:12]}`, basis `{(r.get('basis_sha256') or 'none')[:12]}`, "
            f"{r['status']}",
            "",
            "| batch | degree | columns | irreducible | targets | reducers | built MiB | engine live MiB | dense MiB | new elements | invalidated terms |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        shown = ts if len(ts) <= 24 else sorted(ts, key=lambda b: -b["live_peak_bytes"])[:24]
        for b in sorted(shown, key=lambda b: b["batch"]):
            out.append(
                f"| {b['batch']} | {b['degree']} | {b['columns']:,} | {b['irreducible_before']:,} | "
                f"{b['targets']:,} | {b['reducers']:,} | "
                f"{mib((b['target_entries'] + b['reducer_entries']) * e)} | {mib(b['live_peak_bytes'])} | "
                f"{mib(dense_bytes(b, b['dense_cells'], c))} | {b['elements']:,} | {b['invalidated_terms']:,} |"
            )
        if len(ts) > 24:
            out.append("")
            out.append(f"The 24 batches with the most live bytes, of {len(ts)}.")
        out.append("")
    print("\n".join(out).rstrip())


if __name__ == "__main__":
    main()
