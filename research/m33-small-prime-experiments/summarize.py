#!/usr/bin/env python3
"""#973 K-IR stop-rule tables from the committed records alone: `summarize.py [--check]` -> tables.md.

The stage is the sum of the measured sub-stages. The parallelizable part is the per-seed loop (the
tail sweep and the row's conversion to a polynomial), which is what #845-style candidate finishing
can put on workers; the rest is the minimal-basis selection, the closure, the matrix build and the
final sort. `bound` is the most any worker count `w` can take off: the loop divided perfectly by w.
"""
import argparse
import gzip
import json
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / 'tools'))
import bench_stats as bs  # noqa: E402

SERIAL = ('minimal_ms', 'closure_ms', 'build_ms', 'sort_ms')
LOOP = 'sweep_loop_ms'
STOP_SHARE = 0.35  # Gate A record 1's stop rule
NEEDED_SPEEDUP = 1.53  # Gate A record 1: the stage speedup that gives 8% of the wall at 8 w


def load():
    out = []
    for path in sorted(HERE.glob('records-*.jsonl.gz')):
        out += [json.loads(line) for line in gzip.decompress(path.read_bytes()).decode().splitlines()]
    return out


def ci(xs, label):
    i = bs.paired_ratio(xs, seed=label)
    return i[0], i[1], i[2]


def fmt(t, digits=3):
    return f'{t[0]:.{digits}f} [{t[1]:.{digits}f}, {t[2]:.{digits}f}]'


def tables(records):
    cells = {}
    for r in records:
        cells.setdefault((r['field'], r['name'], r['workers']), []).append(r)
    lines = ['# K-IR stop-rule session: the final interreduction split', '',
             'Generated by `summarize.py` from `records-*.jsonl.gz`. Milliseconds are medians over every '
             'completed attempt, contaminated ones kept (plan §11.6) and counted in brackets; shares and bounds are per-attempt figures, median [95% percentile bootstrap].', '',
             '| row | w | n (contaminated) | digests | wall | minimal | closure | build | loop (of which conversion) '
             '| sort | stage | **loop share** | max stage speedup | max wall cut |',
             '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
    verdicts = []
    for (field, name, w), rs in sorted(cells.items(), key=lambda kv: (kv[0][1], kv[0][0], kv[0][2])):
        ok = [r for r in rs if r['status'] == 'ok']
        clean = ok  # nothing removed; the contaminated count is reported beside n
        digests = {r['basis_m33'] for r in ok}
        med = {k: statistics.median(r['split'][k] for r in clean) for k in SERIAL + (LOOP, 'of_which_conv_ms')}
        stage = [sum(r['split'][k] for k in SERIAL + (LOOP,)) for r in clean]
        share = [r['split'][LOOP] / s for r, s in zip(clean, stage)]
        cut = max(w, 1)
        speedup = [s / (s - r['split'][LOOP] * (1 - 1 / cut)) for r, s in zip(clean, stage)]
        wall_cut = [r['split'][LOOP] * (1 - 1 / cut) / (r['wall_ns'] / 1e6) for r in clean]
        key = f'{field}/{name}@{w}'
        sh = ci(share, key + ':share')
        sp = ci(speedup, key + ':speedup')
        wc = ci(wall_cut, key + ':wall')
        lines.append(
            f'| {field}/{name} | {w} | {len(ok)} ({sum(r["contaminated"] for r in ok)}) | {len(digests)} | '
            f'{statistics.median(r["wall_ns"] for r in clean) / 1e6:.1f} | {med["minimal_ms"]:.1f} | '
            f'{med["closure_ms"]:.1f} | {med["build_ms"]:.1f} | {med[LOOP]:.1f} ({med["of_which_conv_ms"]:.1f}) | '
            f'{med["sort_ms"]:.1f} | {statistics.median(stage):.1f} | **{fmt(sh)}** | '
            f'{fmt(sp) if w > 1 else "—"} | {fmt(wc) if w > 1 else "—"} |')
        if (field, name, w) == ('m31', 'katsura-11', 8):
            verdicts.append(
                f'- **Stop rule** (Katsura-11 / GF(2³¹−1), 8 w): loop share {fmt(sh)} against the 35% floor: '
                f'**{"abandon" if sh[2] < STOP_SHARE else "continue"}**.')
            verdicts.append(
                f'- **Ceiling:** even a perfect 8-way loop gives a stage speedup of at most {fmt(sp)}, against the '
                f'{NEEDED_SPEEDUP}× Gate A needs, and cuts at most {fmt(wc)} of the process wall against 8%.')
    return '\n'.join(lines + [''] + verdicts) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true', help='fail if tables.md is stale')
    args = p.parse_args()
    text = tables(load())
    path = HERE / 'tables.md'
    if args.check:
        if path.read_text() != text:
            sys.exit('tables.md is stale: run summarize.py')
        return
    path.write_text(text)
    print(text)


if __name__ == '__main__':
    main()
