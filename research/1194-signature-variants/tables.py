#!/usr/bin/env python3
"""#1194: tables.md from runs.jsonl.gz (run.sh). Counts only; the clocks are for scale.

    python3 research/1194-signature-variants/tables.py [runs.jsonl.gz] > tables.md
"""
import gzip
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROWS = ["eco-12", "katsura-11", "mq-random-11", "cyclic-7", "sd-hairer-2@p31"]


def cell(r):
    name = f"{r['module']} / {r['rewrite']}"
    return name + (" / reversed" if r.get("reverse") else "")


def load(path):
    records = []
    with gzip.open(path, "rt") as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def fmt(n):
    return f"{n:,}"


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "runs.jsonl.gz"
    records = load(path)
    print("<!-- generated by tables.py from runs.jsonl.gz; do not edit -->")
    print()
    print("## Pairs, rows and products per row and variant")
    print()
    print("Products are batch-elimination multiply-accumulates (`coefficient_products`); "
          "`× base` is against Schreyer / ratio on the same row. `basis` is `ok` when the "
          "`m33-basis-v1` digest equals conventional F4's.")
    for row in ROWS:
        rs = [r for r in records if r.get("name") == row]
        f4 = next((r for r in rs if r.get("engine") == "f4"), None)
        sig = [r for r in rs if r.get("engine") == "sigf4"]
        if not sig:
            continue
        base = next((r for r in sig if cell(r) == "schreyer / ratio"
                     and r.get("status") == "complete"), None)
        print()
        print(f"### {row}")
        print()
        if f4:
            print(f"Conventional F4: {f4['status']}, {fmt(f4['basis_elements'] or 0)} elements, "
                  f"{f4['call_ns'] / 1e6:,.0f} ms.")
            print()
        print("| variant | status | basis | elements | dominated at birth | pairs | product "
              "| Koszul | zero-row | rewrite | duplicate | targets | reducer rows | to zero "
              "| singular | products | × base | on zero rows | ms |")
        print("|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:"
              "|---:|---:|---:|")
        for r in sig:
            s = r.get("statistics") or {}
            ok = (f4 is not None and r.get("basis_m33") is not None
                  and r["basis_m33"] == f4.get("basis_m33"))
            basis = "ok" if ok else ("—" if r.get("status") != "complete" else "DIFFERS")
            if r.get("status") != "complete":
                print(f"| {cell(r)} | {r.get('status')} | {basis} |" + " |" * 16)
                continue
            ratio = (s["coefficient_products"] / base["statistics"]["coefficient_products"]
                     if base else float("nan"))
            print(
                f"| {cell(r)} | complete | {basis} | {fmt(s['elements_added'])} "
                f"| {fmt(s['dominated_at_birth'])} | {fmt(s['pairs_created'])} "
                f"| {fmt(s['rejected_product'])} | {fmt(s['rejected_koszul'])} "
                f"| {fmt(s['rejected_zero_row'])} | {fmt(s['rejected_rewrite'])} "
                f"| {fmt(s['rejected_duplicate'])} | {fmt(s['targets'])} "
                f"| {fmt(s['reducer_rows'])} | {fmt(s['reductions_to_zero'])} "
                f"| {fmt(s['singular_rows'])} | {fmt(s['coefficient_products'])} "
                f"| {ratio:.3f} | {fmt(s['products_on_zero_rows'])} "
                f"| {r['call_ns'] / 1e6:,.0f} |"
            )


if __name__ == "__main__":
    main()
