#!/usr/bin/env python3
"""#1192: count tables from panel.jsonl and families.jsonl.

    python3 research/1192-weight-detector/tables.py > research/1192-weight-detector/tables.md

Counts only, except the last table, whose ratio is of two unpinned laptop walls and is labelled so.
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load(name):
    with open(os.path.join(HERE, name)) as f:
        return [json.loads(line) for line in f if line.strip()]


def stage(row):
    d = row["detector"]
    if d["outcome"].startswith("TooManyGenerators"):
        return "pigeonhole"
    if d["outcome"].startswith("hit") and d["fast_path"]:
        return "fast path"
    if d["lp_solves"] == 0:
        return "screen"
    return "LP search"


def matrix(f4):
    if "error" in f4:
        return "refused: " + f4["error"].split(" ")[0]
    return "%d × %d" % (f4["max_rows"], f4["max_columns"])


def main(out):
    panel = load("panel.jsonl")
    families = load("families.jsonl")
    w = out.write

    w("# #1192 tables\n\nGenerated by `tables.py` from `panel.jsonl` and `families.jsonl`.\n\n")

    w("## 1. Public panel (#1006, 62 problems at p31): where each row is decided\n\n")
    w("| Stage | Rows | Hits | LP solves (sum) |\n|---|---:|---:|---:|\n")
    by = collections.defaultdict(list)
    for r in panel:
        by[stage(r)].append(r)
    for name in ["pigeonhole", "screen", "fast path", "LP search"]:
        rows = by.get(name, [])
        hits = sum(r["detector"]["outcome"].startswith("hit") for r in rows)
        lps = sum(r["detector"]["lp_solves"] for r in rows)
        w("| %s | %d | %d | %d |\n" % (name, len(rows), hits, lps))
    hits = sum(r["detector"]["outcome"].startswith("hit") for r in panel)
    w("| **total** | %d | %d | |\n\n" % (len(panel), hits))

    w("## 2. Rows that reached the LP search\n\n")
    w("| Row | n | m | Outcome | Screen nodes | Candidates | Search nodes | LPs | Pivots | Weights |\n")
    w("|---|---:|---:|---|---:|---:|---:|---:|---:|---|\n")
    for r in by.get("LP search", []):
        d = r["detector"]
        w("| %s | %d | %d | %s | %d | %d | %d | %d | %d | %s |\n" % (
            r["id"], r["variables"], r["generators"], d["outcome"], d["screen_nodes"],
            d["candidates"], d["nodes"], d["lp_solves"], d["lp_pivots"],
            " ".join(map(str, d.get("weights", []))) or "—"))
    w("\n")

    w("## 3. Panel rows with a weight vector: conventional F4, grevlex against weighted\n\n")
    w("Weighted order: the row's weights, ties reverse-lexicographic. Pair selection is by total "
      "degree under both (§1 of the note). Largest matrix is rows × columns.\n\n")
    w("| Row | Weights (source) | grevlex batches | grevlex top pair degree | grevlex largest | "
      "grevlex peak nonzeros | weighted batches | weighted top pair degree | weighted largest | "
      "weighted peak nonzeros |\n")
    w("|---|---|---:|---:|---|---:|---:|---:|---|---:|\n")
    for r in panel:
        for entry in r.get("weighted_f4", []):
            g, f = r["grevlex_f4"], entry["f4"]
            hit = r["detector"].get("weights") == entry["weights"]
            source = "detector" if hit else "homogeneous"
            w("| %s | %s (%s) | %s | %s | %s | %s | %s | %s | %s | %s |\n" % (
                r["id"], " ".join(map(str, entry["weights"])), source,
                g.get("batches", "—"), g.get("max_pair_degree", "—"), matrix(g),
                g.get("max_live_nonzeros", "—"), f.get("batches", "—"),
                f.get("max_pair_degree", "—"), matrix(f),
                f.get("max_live_nonzeros", "—")))
    w("\n")

    w("## 4. Families: F4 and FGLM to lex, grevlex source against the detector's weighted source\n\n")
    w("`D` is the quotient dimension. Both routes' lex bases are asserted equal by the driver.\n\n")
    w("| Row | Detector | Weights | grevlex F4 batches | grevlex largest | grevlex peak nonzeros | "
      "weighted F4 batches | D | FGLM operator entries, grevlex / weighted | FGLM normal forms, "
      "grevlex / weighted |\n")
    w("|---|---|---|---:|---|---:|---:|---:|---|---|\n")
    for r in families:
        d, g, gf = r["detector"], r["grevlex_f4"], r["grevlex_fglm"]
        wf4, wf = r.get("weighted_f4"), r.get("weighted_fglm")
        w("| %s | %s | %s | %d | %s | %d | %s | %d | %s | %s |\n" % (
            r["name"], d["outcome"], " ".join(map(str, d.get("weights", []))) or "—",
            g["batches"], matrix(g), g["max_live_nonzeros"],
            wf4["batches"] if wf4 else "—", gf["quotient_dimension"],
            "%d / %s" % (gf["operator_entries"], wf["operator_entries"] if wf else "—"),
            "%d / %s" % (gf["normal_form_calls"], wf["normal_form_calls"] if wf else "—")))
    w("\n")

    w("## 5. Detection against the grevlex solve, LP-search rows (laptop, unpinned: indicative only)\n\n")
    w("| Row | Outcome | LPs | Detection / grevlex F4 wall |\n|---|---|---:|---:|\n")
    for r in by.get("LP search", []):
        g = r.get("grevlex_f4", {})
        ratio = ("%.2f%%" % (100 * r["detector"]["detect_ns"] / g["call_ns"])
                 if "call_ns" in g else "F4 " + matrix(g))
        w("| %s | %s | %d | %s |\n" % (r["id"], r["detector"]["outcome"],
                                       r["detector"]["lp_solves"], ratio))


if __name__ == "__main__":
    main(sys.stdout)
