/// Lower-degree relations occur, and the schedule goes straight back down to them.
///
/// M22-D's question, as a measurement rather than an argument. F4 selects the lowest pending degree
/// every time, so a relation that creates lower-degree pairs is acted on at the very next batch —
/// but "so it must be exploited" is a claim about the implementation, and this is the counter that
/// checks it.
#[test]
fn test_mutants_occur_and_the_schedule_returns_to_them() {
    type G = Zp2147483647;

    let mut any_mutants = false;
    let mut any_regression = false;
    let mut any_attributed = false;

    for order in ALL_ORDERS {
        for (name, statistics) in [
            (
                "katsura-5",
                f4_with_options(&katsura::<5, G>(), order, &F4Options::default())
                    .expect("within limits")
                    .1,
            ),
            (
                "katsura-6",
                f4_with_options(&katsura::<6, G>(), order, &F4Options::default())
                    .expect("within limits")
                    .1,
            ),
            (
                "cyclic-5",
                f4_with_options(&cyclic::<5, G>(), order, &F4Options::default())
                    .expect("within limits")
                    .1,
            ),
        ] {
            let context = format!("{} under {}", name, order.name());

            // A mutant is a relation below the degree of the batch that found it, so the gap is
            // positive exactly when one occurred.
            assert_eq!(
                statistics.mutant_elements > 0,
                statistics.batches_with_mutants > 0,
                "{}: the element and batch counts disagree",
                context
            );
            assert_eq!(
                statistics.batches_with_mutants > 0,
                statistics.max_mutant_degree_gap > 0,
                "{}: a batch with a mutant must have a positive degree gap",
                context
            );
            assert!(
                statistics.batches_with_mutants <= statistics.batches,
                "{}: more batches with mutants than batches",
                context
            );
            assert!(
                statistics.mutant_elements >= statistics.batches_with_mutants,
                "{}: fewer mutant elements than batches that produced one",
                context
            );
            assert!(
                statistics.regressions_after_mutants <= statistics.degree_regressions,
                "{}: attributed more regressions than occurred",
                context
            );
            assert_eq!(
                statistics.degree_regressions > 0,
                statistics.max_degree_drop > 0,
                "{}: a regression must have a positive drop",
                context
            );

            any_mutants |= statistics.mutant_elements > 0;
            any_regression |= statistics.degree_regressions > 0;
            any_attributed |= statistics.regressions_after_mutants > 0;
        }
    }

    assert!(any_mutants, "no instance produced a lower-degree relation");
    assert!(
        any_regression,
        "no instance ever returned to a lower degree, so nothing exploits a mutant"
    );
    assert!(
        any_attributed,
        "no regression followed a batch that produced a mutant, so the mechanism was never observed"
    );
}

/// The next batch is always at the lowest pending degree — which is why a mutant needs no
/// mechanism.
///
/// The structural half of M22-D's answer. `select_batch` takes the minimum degree available, so a
/// relation that creates a pair below the current degree is selected *next*, before any remaining
/// pair of the current degree. Asserted here on a live queue rather than inferred from the
/// selection code.
#[test]
fn test_a_lower_degree_pair_is_selected_before_the_current_degree_finishes() {
    use crate::grobner::{CriterionCounts, PairCriteria, PairQueue};
    use crate::Monomial;

    // Leading monomials x^3, y^3 — one pair, at degree six.
    let mut leads = vec![
        Monomial::<3>::new(&[3, 0, 0]),
        Monomial::<3>::new(&[0, 3, 0]),
    ];
    let mut counts = CriterionCounts::default();
    let mut queue = PairQueue::seeded_from_leads(&leads, &PairCriteria::NONE, &mut counts);
    assert_eq!(queue.next_degree(), Some(6));

    // Take it, then append a "mutant" of degree one, as a batch at degree six might.
    let batch = queue.select_batch(None);
    assert_eq!(batch.len(), 1);
    leads.push(Monomial::<3>::new(&[0, 0, 1]));
    queue.push_pairs_from_leads(&leads, 2, &PairCriteria::NONE, &mut counts);

    // Its pairs are at degree four, and that is what comes out next — with no mechanism asked for.
    assert_eq!(
        queue.next_degree(),
        Some(4),
        "the lowest pending degree must be the mutant's, not the batch's"
    );
    let next = queue.select_batch(None);
    assert!(
        next.iter().all(|pair| pair.degree == 4),
        "the next batch mixed degrees: {:?}",
        next.iter().map(|p| p.degree).collect::<Vec<_>>()
    );
}

/// `f4_observed_reported` keeps both the observer's view and the statistics of a refusal.
///
/// The two existing entry points each drop one of them: `f4_observed` returns `Err` with no
/// statistics, and `f4_reported` has no observer. A computation that is *expected* not to finish
/// needs both — the statistics to say how large the matrices got, and the observer to say how far
/// the batches got, since F4 has no cooperative time check for a supervisor to read.
#[test]
fn test_observed_and_reported_together() {
    use crate::grobner::f4::{f4_observed_reported, BatchObserver};
    use crate::grobner::pairs::CriticalPair;

    /// Records the selection degree of every batch it is shown.
    struct Watch(Vec<u64>);
    impl<const N: usize, G: FiniteField> BatchObserver<N, G> for Watch {
        fn batch(
            &mut self,
            _basis: &crate::grobner::f4::symbolic::MonicBasis<N, G>,
            pairs: &[CriticalPair<N>],
        ) {
            self.0
                .push(pairs.iter().map(|p| p.lcm.degree()).max().unwrap_or(0));
        }
    }

    let order = MonomialOrder::GradedReverseLexicographic;
    let system = katsura::<5, Zp2147483647>();

    // Completing: the basis is the one the ordinary entry point returns, and the observer saw
    // every batch the statistics counted.
    let mut watch = Watch(Vec::new());
    let (result, statistics) =
        f4_observed_reported(&system, order, &F4Options::default(), &mut watch);
    let basis = result.expect("katsura-5 completes");
    assert_eq!(basis, f4(&system, order).expect("the same system"));
    assert_eq!(watch.0.len(), statistics.batches);
    assert_eq!(
        watch.0.iter().max().copied(),
        Some(statistics.max_pair_degree),
        "the observer's highest selection degree is the reported one"
    );

    // Refusing: the statistics survive, which is the half `f4_observed` drops, and the observer
    // has seen one batch more than was reduced — the one the budget was crossed inside.
    let mut watch = Watch(Vec::new());
    let (result, statistics) = f4_observed_reported(
        &system,
        order,
        &F4Options {
            max_matrix_columns: 40,
            ..F4Options::default()
        },
        &mut watch,
    );
    assert!(matches!(result, Err(F4Error::TooManyColumns { limit: 40 })));
    assert_eq!(
        statistics.bytes_per_entry,
        F4Options::bytes_per_entry::<Zp2147483647>()
    );
    assert_eq!(
        watch.0.len(),
        statistics.batches + 1,
        "the crossing happened inside a batch the observer had already been shown"
    );
}

/// A zero time budget stops the computation, names the degree it reached, and keeps the counters.
///
/// Zero rather than a small duration so the test is not a race: the check is between batches, so
/// the first batch runs and the second is refused, whatever the machine's speed.
#[test]
fn test_a_time_budget_stops_with_the_degree_and_the_counters() {
    use crate::grobner::{f4_reported, StopKind};
    use std::time::Duration;

    let order = MonomialOrder::GradedReverseLexicographic;
    let system = katsura::<5, Zp2147483647>();
    let options = F4Options {
        max_wall_time: Some(Duration::ZERO),
        ..F4Options::default()
    };

    let (result, statistics) = f4_reported(&system, order, &options);
    let Err(F4Error::TimeBudgetExceeded {
        degree,
        elapsed_millis,
        budget_millis,
    }) = result
    else {
        panic!("a zero budget must stop the computation, not {:?}", result);
    };

    // The degree named is the one the refused batch was selected at, which is a real selection
    // degree and not a sentinel.
    assert!(degree >= 2, "{} is not a selection degree", degree);
    assert_eq!(budget_millis, 0);
    assert!(elapsed_millis >= budget_millis);

    // The group-B counters describe the batches that did run. This is the half an abandoned
    // worker thread cannot deliver, and the reason the stop is cooperative.
    assert_eq!(statistics.batches, 1, "exactly the first batch was reduced");
    assert!(statistics.max_matrix_rows > 0);
    assert!(statistics.max_matrix_columns > 0);
    assert!(statistics.max_live_nonzeros > 0);
    assert!(statistics.max_estimated_bytes > 0);
    assert!(statistics.pairs_reduced > 0);
    assert_eq!(
        statistics.bytes_per_entry,
        F4Options::bytes_per_entry::<Zp2147483647>()
    );

    // Type-level, not by name: a consumer that ranks resource stops cannot reach this one.
    let error = result.expect_err("already matched");
    assert_eq!(error.stop_kind(), StopKind::Time);
    assert_ne!(error.stop_kind(), StopKind::Resource);
    assert_eq!(error.limit_name(), "max_wall_time");
}

/// Every other stop is classified as a resource stop, a caller mistake, or a failed certification.
///
/// Guards the distinction the time stop rests on: if a resource variant were ever classified as
/// `Time`, or the time variant as `Resource`, a frontier would start comparing a wall clock
/// against an entry count.
#[test]
fn test_stop_kinds_keep_clocks_and_budgets_apart() {
    use crate::grobner::StopKind;

    for error in [
        F4Error::TooManyRows { limit: 1 },
        F4Error::TooManyColumns { limit: 1 },
        F4Error::TooManyNonzeros {
            nonzeros: 2,
            limit: 1,
        },
        F4Error::TooManyLiveBytes { bytes: 2, limit: 1 },
        F4Error::TooManyBatches { limit: 1 },
        F4Error::TooManyBasisElements {
            elements: 2,
            limit: 1,
        },
    ] {
        assert_eq!(error.stop_kind(), StopKind::Resource, "{:?}", error);
    }
    assert_eq!(
        F4Error::InvalidOptions { reason: "" }.stop_kind(),
        StopKind::Caller
    );
    assert_eq!(
        F4Error::CertificationFailed { reason: "" }.stop_kind(),
        StopKind::Certification
    );
    assert_eq!(
        F4Error::TimeBudgetExceeded {
            degree: 3,
            elapsed_millis: 10,
            budget_millis: 1,
        }
        .stop_kind(),
        StopKind::Time
    );
}

/// No time budget means no stop, and the default leaves one unset.
#[test]
fn test_no_time_budget_by_default() {
    assert_eq!(F4Options::default().max_wall_time, None);

    let order = MonomialOrder::GradedReverseLexicographic;
    let system = katsura::<4, Zp2147483647>();
    let basis = f4(&system, order).expect("katsura-4 completes");
    let (result, _) = f4_reported(&system, order, &F4Options::default());
    assert_eq!(result.expect("the same system completes"), basis);
}

/// Symbolic preprocessing's monomial queue is counted, and its peak is below what it enqueued.
///
/// The counters the memory attribution rests on: `monomials_enqueued` is the pre-deduplication
/// total, so it must exceed the distinct monomials tested, and the queue's high-water mark must
/// not exceed what was ever put in it.
#[test]
fn test_the_monomial_queue_is_counted() {
    let order = MonomialOrder::GradedReverseLexicographic;
    let system = katsura::<5, Zp2147483647>();
    let (_, statistics) = f4_with_options(&system, order, &F4Options::default())
        .expect("katsura-5 completes under the default");

    assert!(statistics.monomials_enqueued > 0);
    assert!(statistics.max_pending_monomials > 0);
    assert!(
        statistics.max_pending_monomials <= statistics.monomials_enqueued,
        "the queue cannot hold more than was enqueued: {} > {}",
        statistics.max_pending_monomials,
        statistics.monomials_enqueued
    );
    assert!(
        statistics.monomials_enqueued > statistics.divisor_queries,
        "every term of every row is enqueued and only the distinct ones are tested: {} vs {}",
        statistics.monomials_enqueued,
        statistics.divisor_queries
    );
}

/// The pair queue's footprint and the basis's peak size are reported, and the heap holds the live
/// pairs plus whatever lazy deletion left behind.
#[test]
fn test_the_unbudgeted_structures_are_reported() {
    let order = MonomialOrder::GradedReverseLexicographic;
    let system = katsura::<5, Zp2147483647>();
    let (basis, statistics) = f4_with_options(&system, order, &F4Options::default())
        .expect("katsura-5 completes under the default");

    let footprint = statistics.peak_pair_queue;
    assert!(footprint.heap_entries > 0);
    assert!(footprint.heap_entries >= footprint.live);

    // The basis is largest at the end of the loop, before interreduction removes the redundant
    // elements, so the peak is at least what came out.
    assert!(statistics.peak_basis_elements >= basis.len());
    assert!(statistics.peak_basis_terms >= statistics.peak_basis_elements);
}
