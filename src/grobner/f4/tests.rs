//! End-to-end tests for the complete F4 algorithm.
//!
//! A reduced Gröbner basis is unique for a given ideal and monomial order, and both engines return
//! theirs sorted by leading monomial, so agreement with `buchberger` is exact equality of
//! sequences — not of sets, and not up to scalars. That makes the existing Buchberger
//! implementation, itself checked against the naive reference and against Groebner.jl, a complete
//! oracle for F4 wherever both can run.
//!
//! The properties are also checked against the definition, so systems nobody has a reference basis
//! for are covered too.

use crate::{
    fields::{PrimeFieldElement64, Zp13, Zp2147483647, Zp541, Zp7},
    grobner::{
        benchmark_systems::{cyclic, katsura, planted},
        buchberger,
        f4::{f4, f4_with_options, F4Error, F4Options},
        reference::buchberger_reference,
        s_polynomial,
    },
    poly::MonomialOrder,
    util::contains_duplicates,
    FiniteField, MultivariatePolynomial, Zero,
};

type F = Zp13;
const VARS: [&str; 3] = ["x", "y", "z"];
const ALL_ORDERS: [MonomialOrder; 3] = [
    MonomialOrder::Lexicographic,
    MonomialOrder::GradedLexicographic,
    MonomialOrder::GradedReverseLexicographic,
];

fn parse(s: &str) -> MultivariatePolynomial<3, F> {
    MultivariatePolynomial::parse(s, VARS).unwrap()
}

fn system(strings: &[&str]) -> Vec<MultivariatePolynomial<3, F>> {
    strings.iter().map(|s| parse(s)).collect()
}

/// The correctness corpus: systems with varied structure, all in three variables.
fn corpus() -> Vec<Vec<&'static str>> {
    vec![
        // A single generator, which leaves nothing to divide by during minimization.
        vec!["x^2 - y"],
        vec!["x + y + z"],
        vec!["x^2 + y", "x^2 + z"],
        vec!["x + y + z", "x*y + x*z + y*z", "x*y*z - 1"],
        vec!["x^2 - y", "x*y - 1"],
        vec!["x^2 + y^2 - 1", "x - y"],
        vec!["x*y - 1", "x - y"],
        vec!["x^2*y + x", "x*y^2 + y"],
        vec!["x^3 - 2*x*y", "x^2*y - 2*y^2 + x"],
        vec!["x + y", "x^2 + z", "y*z - 1"],
        vec!["x*y*z - 1", "x*y - z"],
        vec!["x*z - y^2", "x^3 - z^2"],
        vec!["x^3 - y", "x^2 - z", "x - y*z", "y^2 - 1"],
        // Homogeneous.
        vec!["x^2 + y^2 + z^2", "x*y + y*z"],
        // Inhomogeneous with constant terms.
        vec!["x^2 + y + 1", "y^2 + z + 2", "z^2 + x + 3"],
        // Positive-dimensional: z is unconstrained.
        vec!["x^2 - y", "x*y - 1"],
        // Several generators sharing a leading monomial.
        vec!["x^2 + y", "x^2 + z", "x^2 + y + z"],
        // Relatively prime leading monomials, which the product criterion eliminates.
        vec!["x^2", "y^3"],
        vec!["x^2 - 1", "y^2 - 1", "z^2 - 1"],
        // Degenerate and redundant.
        vec!["x", "x - 1"],
        vec!["x + y", "x + y", "y^2 - 1"],
        vec!["x + y", "3*x + 3*y", "y^2 - 1"],
        vec!["x + y", "y^2 - 1", "x*y + y^2"],
    ]
}

/// Assert the defining properties of a reduced Gröbner basis for the ideal generated by `f`.
fn assert_is_reduced_grobner_basis<const N: usize, G: FiniteField>(
    f: &[MultivariatePolynomial<N, G>],
    order: MonomialOrder,
    context: &str,
) {
    let g = f4(f, order).expect("within limits");
    assert!(
        !g.is_empty(),
        "{}: a nonzero ideal has a nonempty basis",
        context
    );

    // Generator containment: every input lies in the ideal generated by g.
    for p in f.iter().filter(|p| !p.is_zero()) {
        assert!(
            p.normal_form(&g, order).is_zero(),
            "{}: input {} does not reduce to zero modulo the basis",
            context,
            p
        );
    }

    // Buchberger's criterion: g is a Gröbner basis exactly when every S-polynomial of a pair in g
    // reduces to zero modulo g.
    for (i, g_i) in g.iter().enumerate() {
        for g_j in g.iter().skip(i + 1) {
            assert!(
                s_polynomial(g_i, g_j, order)
                    .normal_form(&g, order)
                    .is_zero(),
                "{}: S({}, {}) does not reduce to zero modulo the basis",
                context,
                g_i,
                g_j
            );
        }
    }

    assert!(
        !contains_duplicates(&g),
        "{}: basis contains duplicates",
        context
    );

    for p in &g {
        assert_eq!(
            p.leading_coefficient(order),
            G::ONE,
            "{}: {} is not monic",
            context,
            p
        );
    }

    // Reduced: no monomial of p is divisible by the leading monomial of any other element.
    for (i, p) in g.iter().enumerate() {
        for m in p.terms().keys() {
            for (j, q) in g.iter().enumerate() {
                if i == j {
                    continue;
                }
                assert!(
                    m.checked_div(&q.leading_monomial(order)).is_none(),
                    "{}: monomial {:?} of {} lies in <LT(G \\ {{p}})>, via {}",
                    context,
                    m.exponents(),
                    p,
                    q
                );
            }
        }
    }

    // Canonical order: strictly decreasing leading monomials.
    for window in g.windows(2) {
        assert_eq!(
            order.cmp(
                &window[0].leading_monomial(order),
                &window[1].leading_monomial(order)
            ),
            std::cmp::Ordering::Greater,
            "{}: basis is not sorted by leading monomial",
            context
        );
    }
}

/// F4 returns a reduced Gröbner basis for every system in the corpus, under every order.
#[test]
fn test_f4_returns_a_reduced_grobner_basis() {
    for order in ALL_ORDERS {
        for strings in corpus() {
            let context = format!("{:?} under {}", strings, order.name());
            assert_is_reduced_grobner_basis(&system(&strings), order, &context);
        }
    }
}

/// F4 and Buchberger agree exactly, as sequences, on the whole corpus under every order.
#[test]
fn test_f4_agrees_with_buchberger() {
    for order in ALL_ORDERS {
        for strings in corpus() {
            let f = system(&strings);
            assert_eq!(
                f4(&f, order).expect("within limits"),
                buchberger(&f, order),
                "{:?} under {}",
                strings,
                order.name()
            );
        }
    }
}

