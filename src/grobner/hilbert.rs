    /// A comparison records the first degree where the model and the measurement part company.
    #[test]
    fn test_the_comparison_finds_the_first_disagreement() {
        // <x^2, x*y, x*z> = x * <x, y, z>: three quadratics in three variables, and about as far
        // from a regular sequence as three forms can be — `x` is a zero divisor on the quotient by
        // the first, so the second and third contribute nothing new in degree two beyond what the
        // first already implies. The model, which for `m = n` is the regular-sequence formula
        // `(1 + z)^3`, predicts the quotient dies by degree four; in fact the whole subring in
        // `y, z` survives forever.
        let system: Vec<MultivariatePolynomial<3, F>> = ["x^2", "x*y", "x*z"]
            .iter()
            .map(|s| MultivariatePolynomial::parse(s, ["x", "y", "z"]).unwrap())
            .collect();
        assert!(is_homogeneous(&system));
        let basis = f4(&system, GREVLEX).expect("within limits");

        let comparison = HilbertComparison::new(&basis, GREVLEX, &[2, 2, 2], 6).expect("in range");

        assert_eq!(comparison.degrees.len(), 7);
        assert_eq!(comparison.degrees[0].observed, 1, "H(0) = 1 always");
        assert_eq!(comparison.degrees[1].observed, 3, "the three variables");
        // Both agree up to degree two: y^2, y*z, z^2 survive and the model expects three.
        assert!(comparison.degrees[0].agrees());
        assert!(comparison.degrees[1].agrees());
        assert_eq!(comparison.degrees[2].observed, 3);
        assert!(comparison.degrees[2].agrees());

        // Degree three is where it parts company: the model says one class is left, and there are
        // four — y^3, y^2*z, y*z^2, z^3.
        assert_eq!(
            comparison.first_disagreement,
            Some((3, 1, 4)),
            "predicted 1, observed 4"
        );
        assert_eq!(
            comparison.degrees[3].error(),
            -3,
            "the model underestimates"
        );
        assert!(comparison.agreement_rate() < 1.0);

        // And the model's degree of regularity is wrong in the direction that matters: it says the
        // computation is finished by degree four, and the ideal is positive-dimensional.
        assert_eq!(comparison.predicted_degree_of_regularity, Some(4));
        assert_eq!(
            comparison.observed_top_degree(),
            Some(6),
            "nonzero at every degree computed, because the quotient never dies"
        );
    }

