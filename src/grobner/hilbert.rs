//! Hilbert functions, exactly from a computed basis and predictably from a semiregularity model.
//!
//! For a homogeneous ideal `I ⊆ R = F[x_1, …, x_n]` the Hilbert function is
//!
//! ```text
//! H_I(d) = dim_F (R/I)_d
//! ```
//!
//! — how many independent residue classes remain in each degree. It is what the Hilbert-driven
//! strategies of #74 are stated in: `dim I_d = dim R_d − H_I(d)` bounds how many independent rows a
//! degree-`d` Macaulay matrix can possibly contribute, so a prediction of `H_I` is a prediction of
//! when further reductions at that degree must reduce to zero.
//!
//! **This module is diagnostic.** Nothing here discards work, and nothing correctness-critical may
//! consult a prediction — see [`SemiregularSeries`] for why the prediction is a prediction.
//!
//! # Exactly, from a leading-term ideal
//!
//! `H_I` depends only on the leading-term ideal `L = LT(I)` under any order, because the standard
//! monomials of `L` are a vector-space basis of `R/I` in each degree. So the exact Hilbert function
//! of an ideal whose Gröbner basis has been computed is the Hilbert function of a *monomial* ideal,
//! which is what [`HilbertSeries::of_monomial_ideal`] computes.
//!
//! It does not enumerate. Counting the degree-`d` monomials outside `L` directly costs
//! `binomial(n + d − 1, d)` divisibility sweeps, which is 20 million at `n = 20, d = 10` and worse
//! immediately after. Instead the series is built in closed form, as
//!
//! ```text
//! H_I(z) = numerator(z) / (1 − z)^n
//! ```
//!
//! with `numerator` a polynomial with integer — often negative — coefficients, computed by the
//! standard recursion on the exact sequence
//!
//! ```text
//! 0 → R/(L : p) --·p--> R/L → R/(L + <p>) → 0
//! ```
//!
//! which gives `num(L) = num(L + <p>) + z^deg(p) · num(L : p)`. See Bigatti, A. M. (1997),
//! *Computation of Hilbert–Poincaré series*, J. Pure Appl. Algebra 119, 237–253, and Bayer, D.,
//! Stillman, M. (1992), *Computation of Hilbert functions*, J. Symbolic Computation 14, 31–50.
//!
//! The recursion is bounded by a node budget rather than trusted to be small: it is exponential in
//! the worst case, and an unbounded recursion in a diagnostic tool is a way to lose a measurement
//! run rather than a way to get an answer.
//!
//! # Inhomogeneous systems
//!
//! The definition above requires a homogeneous ideal. The Fukuoka MQ instances and the Poseidon
//! CICO systems are **not** homogeneous, and this module does not pretend otherwise. What it offers
//! is [`top_forms`], the ideal generated by each generator's highest-degree homogeneous component —
//! which is the object the semiregularity model for MQ is about, and is **not** the same ideal as
//! the one you started with, nor its homogenization. Any figure taken through `top_forms` is a
//! figure about that system, and every table in `examples/hilbert_study.rs` says so.

use std::collections::BTreeMap;

use crate::{poly::MonomialOrder, FiniteField, Monomial, MultivariatePolynomial};

/// Why a Hilbert computation did not finish.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum HilbertError {
    /// The recursion visited more nodes than allowed.
    ///
    /// Carries the budget rather than the count, for the same reason
    /// [`F4Error::TooManyRows`](crate::grobner::F4Error::TooManyRows) does: the recursion stops at
    /// the crossing, so any count it could report is the budget and not the size the computation
    /// would have reached.
    TooManyNodes { limit: usize },

    /// A coefficient or a dimension exceeded `i128`.
    ///
    /// Reported rather than wrapped. A Hilbert function that silently became negative would look
    /// like a mathematical finding.
    Overflow,

    /// A series would have needed more coefficients than allowed.
    ///
    /// The *allocation* bound, as distinct from [`Self::TooManyNodes`]'s recursion bound. A
    /// numerator's length grows with the degrees of the generators, and a generator's exponents are
    /// `u32` — so a single `x^100000000` makes an honest expansion tens of gigabytes before F4
    /// builds its first matrix, and F4's matrix budgets do not cover preprocessing. Refused here,
    /// cheaply, rather than terminating the process.
    TooManyCoefficients { needed: u64, limit: usize },
}

impl std::fmt::Display for HilbertError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::TooManyNodes { limit } => write!(
                f,
                "the Hilbert recursion needed more than the {} nodes allowed",
                limit
            ),
            Self::Overflow => write!(f, "a Hilbert coefficient exceeded the integer range"),
            Self::TooManyCoefficients { needed, limit } => write!(
                f,
                "a Hilbert series needed {} coefficients, over the limit of {}",
                needed, limit
            ),
        }
    }
}

impl std::error::Error for HilbertError {}

/// The default node budget for [`HilbertSeries::of_monomial_ideal`].
///
/// Generous enough for every leading-term ideal in this repository's corpus — the largest, Fukuoka
/// type VI `n=10` specialized, has 69 generators in ten variables and finishes in a few thousand
/// nodes — and small enough to fail in under a second rather than filling a workstation.
pub const DEFAULT_NODE_BUDGET: usize = 2_000_000;

/// The most coefficients any series in this module may hold.
///
/// A separate budget from [`DEFAULT_NODE_BUDGET`], because it bounds a different resource: that one
/// bounds the recursion's *breadth* and this one bounds a single `Vec`'s *length*. A numerator's
/// length is one plus the summed degrees of the generators, and an expansion's is the degree range
/// asked for — both of which scale with input exponents that are `u32`, so neither is small by
/// construction.
///
/// One million `i128` coefficients is 16 MB, which is an order of magnitude under the 320 MB that
/// `F4Options::default` allows a matrix and is far more than any ideal in this repository's corpus
/// needs: the widest numerator in the M22 corpus is a few hundred terms. A crossing is
/// [`HilbertError::TooManyCoefficients`], and in a Hilbert-driven F4 that makes the prediction
/// unavailable and the computation ordinary — counted, never fatal.
pub const DEFAULT_COEFFICIENT_BUDGET: usize = 1_000_000;

/// Reject a length no series here is allowed to reach.
fn check_length(needed: u64, limit: usize) -> Result<(), HilbertError> {
    if needed > limit as u64 {
        Err(HilbertError::TooManyCoefficients { needed, limit })
    } else {
        Ok(())
    }
}

/// A Hilbert series as `numerator(z) / (1 − z)^variables`.
///
/// The numerator is exact and usually short; the quotient's coefficients — the Hilbert function
/// itself — are produced on demand by [`HilbertSeries::function`], because for a
/// positive-dimensional ideal there are infinitely many nonzero ones.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct HilbertSeries {
    /// `numerator[j]` is the coefficient of `z^j`. Integer, and frequently negative.
    numerator: Vec<i128>,

    /// The number of variables, i.e. the power of `(1 − z)` in the denominator.
    variables: usize,
}

impl HilbertSeries {
    /// The series of `R/R` — the zero ring — for a ring in `variables` variables.
    ///
    /// `numerator = 0`, so every Hilbert value is zero. This is what the unit ideal gives.
    pub fn zero(variables: usize) -> Self {
        Self {
            numerator: vec![0],
            variables,
        }
    }

    /// The series of `R` itself: `1 / (1 − z)^variables`.
    pub fn polynomial_ring(variables: usize) -> Self {
        Self {
            numerator: vec![1],
            variables,
        }
    }

    /// The exact Hilbert series of `R/<generators>` for a **monomial** ideal, under
    /// [`DEFAULT_NODE_BUDGET`].
    ///
    /// # Errors
    /// [`HilbertError::TooManyNodes`] if the recursion is too large, or
    /// [`HilbertError::Overflow`].
    pub fn of_monomial_ideal<const N: usize>(
        generators: &[Monomial<N>],
    ) -> Result<Self, HilbertError> {
        Self::of_monomial_ideal_within(generators, DEFAULT_NODE_BUDGET)
    }

    /// As [`HilbertSeries::of_monomial_ideal`], under the given node budget.
    pub fn of_monomial_ideal_within<const N: usize>(
        generators: &[Monomial<N>],
        budget: usize,
    ) -> Result<Self, HilbertError> {
        let minimal = minimalize(generators);
        let mut nodes = 0;
        let numerator = numerator_of(&minimal, budget, &mut nodes)?;
        Ok(Self {
            numerator,
            variables: N,
        })
    }

    /// The exact Hilbert series of the ideal a Gröbner basis generates, from its leading monomials.
    ///
    /// Correct for a **homogeneous** ideal. For an inhomogeneous one this is the Hilbert function
    /// of the leading-term ideal, which is a well-defined monomial ideal and a legitimate object —
    /// it is just not the graded structure of the ideal you started with. See the module docs.
    ///
    /// # Errors
    /// As [`HilbertSeries::of_monomial_ideal`].
    pub fn of_basis<const N: usize, F: FiniteField>(
        basis: &[MultivariatePolynomial<N, F>],
        order: MonomialOrder,
    ) -> Result<Self, HilbertError> {
        let leads: Vec<Monomial<N>> = basis
            .iter()
            .filter(|p| !p.is_zero())
            .map(|p| p.leading_monomial(order))
            .collect();
        Self::of_monomial_ideal(&leads)
    }

    /// The numerator's coefficients, lowest degree first.
    pub fn numerator(&self) -> &[i128] {
        &self.numerator
    }

    /// The number of variables.
    pub fn variables(&self) -> usize {
        self.variables
    }

    /// `H(degree) = dim_F (R/I)_degree`.
    ///
    /// Expanding `numerator / (1 − z)^n` coefficient by coefficient: the `d`th coefficient of
    /// `1/(1 − z)^n` is `binomial(n − 1 + d, n − 1)`, so
    /// `H(d) = Σ_j numerator[j] · binomial(n − 1 + d − j, n − 1)`.
    ///
    /// # Errors
    /// [`HilbertError::Overflow`] if the sum or a binomial exceeds `i128`.
    pub fn function(&self, degree: u64) -> Result<i128, HilbertError> {
        if self.variables == 0 {
            // F[] has one monomial, in degree zero.
            return Ok(if degree == 0 {
                self.numerator.first().copied().unwrap_or(0)
            } else {
                0
            });
        }

        let mut total: i128 = 0;
        for (shift, coefficient) in self.numerator.iter().enumerate() {
            if *coefficient == 0 || shift as u64 > degree {
                continue;
            }
            let remaining = degree - shift as u64;
            let weight = binomial(
                remaining + self.variables as u64 - 1,
                self.variables as u64 - 1,
            )?;
            total = total
                .checked_add(
                    coefficient
                        .checked_mul(weight)
                        .ok_or(HilbertError::Overflow)?,
                )
                .ok_or(HilbertError::Overflow)?;
        }
        Ok(total)
    }

    /// `H(0), …, H(up_to)`.
    ///
    /// # Errors
    /// [`HilbertError::TooManyCoefficients`] if `up_to` asks for more than
    /// [`DEFAULT_COEFFICIENT_BUDGET`] values, and otherwise as [`HilbertSeries::function`].
    pub fn values(&self, up_to: u64) -> Result<Vec<i128>, HilbertError> {
        check_length(up_to.saturating_add(1), DEFAULT_COEFFICIENT_BUDGET)?;
        (0..=up_to).map(|d| self.function(d)).collect()
    }

    /// `dim_F I_degree = dim_F R_degree − H(degree)`.
    ///
    /// **The quantity a Hilbert-driven selection is about.** It is the rank of the degree-`d` part
    /// of the ideal, so it caps how many independent relations of degree `d` exist at all — and
    /// therefore how many independent rows a degree-`d` Macaulay matrix can contribute, however
    /// many pairs are put into it.
    ///
    /// # Errors
    /// As [`HilbertSeries::function`].
    pub fn ideal_dimension(&self, degree: u64) -> Result<i128, HilbertError> {
        Ok(monomials_of_degree(self.variables, degree)? - self.function(degree)?)
    }

    /// `Σ_d H(d)`, i.e. `dim_F R/I`, when the ideal is zero-dimensional.
    ///
    /// `None` when it is not, in which case the sum diverges. The bound comes from the ideal's own
    /// generators rather than from a search: a zero-dimensional monomial ideal's minimal generators
    /// include a pure power `x_i^{a_i}` of every variable, and no standard monomial can have
    /// `x_i`-exponent above `a_i − 1`, so every standard monomial has degree at most
    /// `Σ (a_i − 1)`.
    ///
    /// # Errors
    /// As [`HilbertSeries::function`].
    pub fn quotient_dimension<const N: usize>(
        &self,
        generators: &[Monomial<N>],
    ) -> Result<Option<i128>, HilbertError> {
        let Some(bound) = socle_degree_bound(generators) else {
            return Ok(None);
        };
        // The bound is a sum of generator exponents, so it is as large as the input makes it. The
        // loop allocates nothing, but it is still work proportional to that bound, and a caller who
        // asked for a dimension should get a refusal rather than an hour.
        check_length(bound.saturating_add(1), DEFAULT_COEFFICIENT_BUDGET)?;
        let mut total: i128 = 0;
        for degree in 0..=bound {
            total = total
                .checked_add(self.function(degree)?)
                .ok_or(HilbertError::Overflow)?;
        }
        Ok(Some(total))
    }
}

/// `dim_F R_degree`: the number of monomials of exactly that degree in `variables` variables.
pub fn monomials_of_degree(variables: usize, degree: u64) -> Result<i128, HilbertError> {
    if variables == 0 {
        return Ok(if degree == 0 { 1 } else { 0 });
    }
    binomial(degree + variables as u64 - 1, variables as u64 - 1)
}

/// `binomial(n, k)`, computed so that the intermediate products stay small.
///
/// Multiply-then-divide in a loop, taking `k` to be the smaller of `k` and `n − k`. Each partial
/// product is divisible by its divisor, so the division is exact and no rational arithmetic is
/// needed.
fn binomial(n: u64, k: u64) -> Result<i128, HilbertError> {
    if k > n {
        return Ok(0);
    }
    let k = k.min(n - k);
    let mut result: i128 = 1;
    for step in 0..k {
        result = result
            .checked_mul((n - step) as i128)
            .ok_or(HilbertError::Overflow)?;
        // Exact: after multiplying by (n - step), the running product is binomial(n, step + 1)
        // times (step + 1)!/(step + 1)! — divisible by step + 1.
        result /= (step + 1) as i128;
    }
    Ok(result)
}

/// `generators` with every element divisible by another removed, and duplicates dropped.
///
/// The minimal generating set of the monomial ideal, which is unique. The recursion's termination
/// argument is stated over minimal generators, so this is not an optimization.
fn minimalize<const N: usize>(generators: &[Monomial<N>]) -> Vec<Monomial<N>> {
    let mut sorted: Vec<Monomial<N>> = generators.to_vec();
    // Ascending by degree, so a generator is only ever tested against ones that could divide it.
    sorted.sort_by_key(|m| (m.degree(), *m));
    sorted.dedup();

    let mut minimal: Vec<Monomial<N>> = Vec::new();
    for candidate in sorted {
        if !minimal.iter().any(|kept| divides(kept, &candidate)) {
            minimal.push(candidate);
        }
    }
    minimal
}

/// True if `a` divides `b`.
fn divides<const N: usize>(a: &Monomial<N>, b: &Monomial<N>) -> bool {
    a.exponents()
        .iter()
        .zip(b.exponents().iter())
        .all(|(x, y)| x <= y)
}

/// True if no two of `generators` share a variable.
fn pairwise_coprime<const N: usize>(generators: &[Monomial<N>]) -> bool {
    let mut seen = [false; N];
    for generator in generators {
        for (variable, exponent) in generator.exponents().iter().enumerate() {
            if *exponent == 0 {
                continue;
            }
            if seen[variable] {
                return false;
            }
            seen[variable] = true;
        }
    }
    true
}

/// `numerator(z)` for the monomial ideal generated by `minimal`, which must be minimalized.
///
/// # The recursion, and why it terminates
///
/// Three base cases, then the exact sequence. The pivot is a **single variable** `x_i` dividing at
/// least two of the generators, which exists whenever they are not pairwise coprime:
///
/// - `L + <x_i>` minimalizes to `{x_i} ∪ {g : x_i ∤ g}`, and `x_i` is coprime to all of those, so
///   its numerator is `(1 − z)` times the sub-ideal's. Since at least two generators were dropped
///   and `x_i` itself cannot have been a minimal generator — if it were, nothing else could be
///   divisible by it — the generators removed have total degree at least four against the one added.
/// - `L : x_i` reduces the `x_i`-exponent of every generator that has one, so at least two
///   generators lose a degree.
///
/// Both branches therefore strictly decrease the total degree of the minimal generators, which is a
/// non-negative integer. A larger pivot would shorten the recursion and is deliberately not used:
/// the exponent-one pivot is the one whose termination argument is short enough to check.
fn numerator_of<const N: usize>(
    minimal: &[Monomial<N>],
    budget: usize,
    nodes: &mut usize,
) -> Result<Vec<i128>, HilbertError> {
    *nodes += 1;
    if *nodes > budget {
        return Err(HilbertError::TooManyNodes { limit: budget });
    }

    // R/0 = R.
    if minimal.is_empty() {
        return Ok(vec![1]);
    }

    // A regular sequence of monomials: the numerator factors.
    if pairwise_coprime(minimal) {
        let mut numerator = vec![1i128];
        for generator in minimal {
            numerator = multiply_by_one_minus_power(&numerator, generator.degree())?;
        }
        return Ok(numerator);
    }

    // The pivot: the variable dividing the most generators. Any variable dividing at least two
    // would do; the most-frequent one keeps the recursion shallow.
    let mut occurrences = [0usize; N];
    for generator in minimal {
        for (variable, exponent) in generator.exponents().iter().enumerate() {
            if *exponent > 0 {
                occurrences[variable] += 1;
            }
        }
    }
    let pivot = (0..N)
        .max_by_key(|variable| occurrences[*variable])
        .expect("a non-empty generating set has a variable");
    debug_assert!(
        occurrences[pivot] >= 2,
        "generators that are not pairwise coprime share a variable"
    );

    // L + <x_pivot>, as the coprime factor (1 - z) times the generators x_pivot does not divide.
    let untouched: Vec<Monomial<N>> = minimal
        .iter()
        .filter(|g| g.exponents()[pivot] == 0)
        .copied()
        .collect();
    let sum = multiply_by_one_minus_power(&numerator_of(&untouched, budget, nodes)?, 1)?;

    // L : x_pivot.
    let quotient: Vec<Monomial<N>> = minimal
        .iter()
        .map(|g| {
            let mut exponents = [0u32; N];
            exponents.copy_from_slice(g.exponents());
            exponents[pivot] = exponents[pivot].saturating_sub(1);
            Monomial::new(&exponents)
        })
        .collect();
    let colon = numerator_of(&minimalize(&quotient), budget, nodes)?;

    // num(L) = num(L + <x>) + z^1 * num(L : x).
    add_shifted(sum, &colon, 1)
}

/// `numerator * (1 − z^power)`.
///
/// The length grows by `power`, which comes from a generator's degree and is therefore as large as
/// a `u32` exponent sum allows. Bounded, and computed in `u64` so the bound is checked before the
/// allocation rather than after it has already wrapped.
fn multiply_by_one_minus_power(numerator: &[i128], power: u64) -> Result<Vec<i128>, HilbertError> {
    let needed = (numerator.len() as u64)
        .checked_add(power)
        .ok_or(HilbertError::Overflow)?;
    check_length(needed, DEFAULT_COEFFICIENT_BUDGET)?;
    let shift = power as usize;
    let mut result = vec![0i128; numerator.len() + shift];
    for (index, coefficient) in numerator.iter().enumerate() {
        result[index] = result[index]
            .checked_add(*coefficient)
            .ok_or(HilbertError::Overflow)?;
        result[index + shift] = result[index + shift]
            .checked_sub(*coefficient)
            .ok_or(HilbertError::Overflow)?;
    }
    Ok(result)
}

/// `left + z^shift * right`.
fn add_shifted(
    mut left: Vec<i128>,
    right: &[i128],
    shift: usize,
) -> Result<Vec<i128>, HilbertError> {
    if left.len() < right.len() + shift {
        left.resize(right.len() + shift, 0);
    }
    for (index, coefficient) in right.iter().enumerate() {
        left[index + shift] = left[index + shift]
            .checked_add(*coefficient)
            .ok_or(HilbertError::Overflow)?;
    }
    Ok(left)
}

/// `Σ (a_i − 1)` where `x_i^{a_i}` is a minimal generator, or `None` if some variable has no pure
/// power among the generators.
///
/// An upper bound on the degree of a standard monomial, hence on where the Hilbert function can
/// still be nonzero. `None` is exactly the positive-dimensional case.
fn socle_degree_bound<const N: usize>(generators: &[Monomial<N>]) -> Option<u64> {
    let minimal = minimalize(generators);
    let mut total = 0u64;
    for variable in 0..N {
        let power = minimal
            .iter()
            .filter(|g| {
                g.exponents()
                    .iter()
                    .enumerate()
                    .all(|(other, exponent)| other == variable || *exponent == 0)
            })
            .map(|g| g.exponents()[variable] as u64)
            .min()?;
        total += power.saturating_sub(1);
    }
    Some(total)
}

/// The predicted Hilbert series of a semiregular sequence of the given degrees.
///
/// For a homogeneous sequence `f_1, …, f_m` of degrees `d_1, …, d_m` in `n` variables, the formal
/// expression is
///
/// ```text
/// Π (1 − z^{d_i}) / (1 − z)^n
/// ```
///
/// which is **exact** when the sequence is a regular sequence — in particular it requires `m ≤ n`.
/// For `m > n` no sequence is regular in the ordinary sense, and the expression's coefficients go
/// negative; the semiregularity model takes the *positive truncation*, i.e. the series up to but
/// not including the first non-positive coefficient, and predicts zero beyond it.
///
/// # This is a prediction
///
/// It is exact under hypotheses — regularity, or semiregularity in the sense of Bardet, Faugère
/// and Salvy — that are **conjectural for generic systems and simply false for structured ones**.
/// Nothing in this crate may discard work on the strength of it. See
/// `docs/research/hilbert-functions.md` for where it agrees with the measured Hilbert function on
/// this repository's corpus and where it does not.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct SemiregularSeries {
    /// `coefficients[d]` is the predicted `H(d)`, truncated at zero from the first non-positive
    /// term onward.
    coefficients: Vec<i128>,

    /// The first degree at which the untruncated expansion is non-positive, if one was reached.
    ///
    /// The model's **degree of regularity**: the first degree at which a semiregular sequence is
    /// predicted to have no residue classes left, hence the degree at which a Gröbner computation
    /// on such a system is predicted to finish. `None` means the expansion stayed positive
    /// throughout the range computed, which says the range was too short rather than that the
    /// degree does not exist.
    degree_of_regularity: Option<u64>,

    /// The untruncated expansion, so that the sign of the first negative term is inspectable.
    raw: Vec<i128>,
}

impl SemiregularSeries {
    /// The prediction for `m` forms of the given degrees in `variables` variables, expanded to
    /// `up_to`.
    ///
    /// # Errors
    /// [`HilbertError::Overflow`].
    pub fn new(variables: usize, degrees: &[u64], up_to: u64) -> Result<Self, HilbertError> {
        let mut numerator = vec![1i128];
        for degree in degrees {
            numerator = multiply_by_one_minus_power(&numerator, *degree)?;
        }
        let series = HilbertSeries {
            numerator,
            variables,
        };
        let raw = series.values(up_to)?;

        let mut degree_of_regularity = None;
        let mut coefficients = Vec::with_capacity(raw.len());
        for (degree, value) in raw.iter().enumerate() {
            if degree_of_regularity.is_none() && *value <= 0 {
                degree_of_regularity = Some(degree as u64);
            }
            coefficients.push(if degree_of_regularity.is_some() {
                0
            } else {
                *value
            });
        }

        Ok(Self {
            coefficients,
            degree_of_regularity,
            raw,
        })
    }

    /// The prediction for `count` quadratics in `variables` variables.
    ///
    /// The MQ case: `(1 − z^2)^m / (1 − z)^n`.
    ///
    /// # Errors
    /// As [`SemiregularSeries::new`].
    pub fn quadratics(variables: usize, count: usize, up_to: u64) -> Result<Self, HilbertError> {
        Self::new(variables, &vec![2; count], up_to)
    }

    /// The predicted `H(degree)`, zero at and above the degree of regularity.
    pub fn function(&self, degree: u64) -> i128 {
        self.coefficients.get(degree as usize).copied().unwrap_or(0)
    }

    /// The untruncated expansion at `degree`, which may be negative.
    pub fn raw(&self, degree: u64) -> i128 {
        self.raw.get(degree as usize).copied().unwrap_or(0)
    }

    /// The first degree at which the untruncated expansion is non-positive.
    ///
    /// The model's degree of regularity. See the field documentation for what `None` means.
    pub fn degree_of_regularity(&self) -> Option<u64> {
        self.degree_of_regularity
    }

    /// The predicted truncated values, lowest degree first.
    pub fn values(&self) -> &[i128] {
        &self.coefficients
    }
}

/// Each generator's highest-degree homogeneous component.
///
/// **A different ideal.** `top_forms` of `{x^2 + y}` is `{x^2}`, whose variety is a line where the
/// original's is a parabola; the two ideals are unrelated as ideals. What the construction is for is
/// that the semiregularity model in [`SemiregularSeries`] is a statement about a homogeneous
/// sequence, and for an MQ system the sequence the model is applied to in the literature is the
/// sequence of top forms. A figure taken through here is a figure about the top-form system, and
/// saying so is the caller's responsibility.
///
/// A generator that is zero is dropped, as everywhere else in this crate.
pub fn top_forms<const N: usize, F: FiniteField>(
    system: &[MultivariatePolynomial<N, F>],
) -> Vec<MultivariatePolynomial<N, F>> {
    system
        .iter()
        .filter(|p| !p.is_zero())
        .map(|p| {
            let degree = p.degree();
            let terms: Vec<(Monomial<N>, F)> = p
                .terms()
                .iter()
                .filter(|(monomial, _)| monomial.degree() == degree)
                .map(|(monomial, coefficient)| (*monomial, *coefficient))
                .collect();
            MultivariatePolynomial::new(&terms)
        })
        .collect()
}

/// True if every generator is homogeneous, i.e. all its monomials have one degree.
pub fn is_homogeneous<const N: usize, F: FiniteField>(
    system: &[MultivariatePolynomial<N, F>],
) -> bool {
    system.iter().filter(|p| !p.is_zero()).all(|p| {
        let degree = p.degree();
        p.terms().keys().all(|monomial| monomial.degree() == degree)
    })
}

/// Observed against predicted, at one degree.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct DegreeAgreement {
    /// The degree.
    pub degree: u64,

    /// `dim_F R_degree`, for scale.
    pub ambient: i128,

    /// The exact Hilbert function of the computed leading-term ideal.
    pub observed: i128,

    /// The semiregular model's prediction, truncated at the degree of regularity.
    pub predicted: i128,

    /// `dim_F I_degree` observed: the rank the degree really has available.
    pub observed_ideal_dimension: i128,

    /// `dim_F I_degree` as the model predicts it.
    pub predicted_ideal_dimension: i128,
}

impl DegreeAgreement {
    /// True if the prediction matched exactly.
    pub fn agrees(&self) -> bool {
        self.observed == self.predicted
    }

    /// `predicted − observed`, the signed error.
    ///
    /// Positive means the model expected more residue classes than there are, i.e. it
    /// **underestimates** how much the ideal contains — which is the direction that would make a
    /// Hilbert-driven selection skip pairs it needed.
    pub fn error(&self) -> i128 {
        self.predicted - self.observed
    }
}

/// A degree-by-degree comparison of a measured Hilbert function against the semiregular model.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct HilbertComparison {
    /// One entry per degree, ascending from zero.
    pub degrees: Vec<DegreeAgreement>,

    /// The model's degree of regularity, if the expansion reached it.
    pub predicted_degree_of_regularity: Option<u64>,

    /// The first degree at which observed and predicted differ, with both values.
    pub first_disagreement: Option<(u64, i128, i128)>,
}

impl HilbertComparison {
    /// Compare the exact Hilbert function of `basis`'s leading-term ideal against the semiregular
    /// prediction for `degrees` forms, over `0..=up_to`.
    ///
    /// `basis` should be a Gröbner basis of a **homogeneous** ideal for the observed values to be
    /// the ideal's graded dimensions; `degrees` should be the degrees of the generators the model
    /// is about. Neither is checked here, because neither can be: the comparison is between two
    /// numbers, and whether they are numbers about the same object is the caller's claim.
    ///
    /// # Errors
    /// As [`HilbertSeries::of_basis`] and [`SemiregularSeries::new`].
    pub fn new<const N: usize, F: FiniteField>(
        basis: &[MultivariatePolynomial<N, F>],
        order: MonomialOrder,
        degrees: &[u64],
        up_to: u64,
    ) -> Result<Self, HilbertError> {
        let observed = HilbertSeries::of_basis(basis, order)?;
        let predicted = SemiregularSeries::new(N, degrees, up_to)?;

        let mut entries = Vec::with_capacity(up_to as usize + 1);
        let mut first_disagreement = None;
        for degree in 0..=up_to {
            let ambient = monomials_of_degree(N, degree)?;
            let entry = DegreeAgreement {
                degree,
                ambient,
                observed: observed.function(degree)?,
                predicted: predicted.function(degree),
                observed_ideal_dimension: observed.ideal_dimension(degree)?,
                predicted_ideal_dimension: ambient - predicted.function(degree),
            };
            if !entry.agrees() && first_disagreement.is_none() {
                first_disagreement = Some((degree, entry.predicted, entry.observed));
            }
            entries.push(entry);
        }

        Ok(Self {
            degrees: entries,
            predicted_degree_of_regularity: predicted.degree_of_regularity(),
            first_disagreement,
        })
    }

    /// The highest degree at which the observed Hilbert function is nonzero, if any.
    ///
    /// For a zero-dimensional homogeneous ideal this is the top degree of `R/I`, and the honest
    /// observed counterpart to the model's degree of regularity — the model's figure is the first
    /// degree with *nothing left*, so the two are expected to differ by one.
    pub fn observed_top_degree(&self) -> Option<u64> {
        self.degrees
            .iter()
            .filter(|entry| entry.observed != 0)
            .map(|entry| entry.degree)
            .next_back()
    }

    /// Degrees where the two agree, against degrees compared.
    pub fn agreement_rate(&self) -> f64 {
        if self.degrees.is_empty() {
            return 0.0;
        }
        let agreed = self.degrees.iter().filter(|e| e.agrees()).count();
        agreed as f64 / self.degrees.len() as f64
    }
}

/// New leading monomials per degree, from a computed Gröbner basis.
///
/// The observed counterpart to a prediction of "how many new basis elements will degree `d`
/// produce": the minimal generators of the leading-term ideal, counted by degree. This is a
/// property of the *ideal*, not of a run — an F4 computation may find a given generator at a higher
/// degree than the generator's own degree, and M22-0's `DegreeProfile` records that separately.
pub fn leading_generators_by_degree<const N: usize, F: FiniteField>(
    basis: &[MultivariatePolynomial<N, F>],
    order: MonomialOrder,
) -> BTreeMap<u64, usize> {
    let leads: Vec<Monomial<N>> = basis
        .iter()
        .filter(|p| !p.is_zero())
        .map(|p| p.leading_monomial(order))
        .collect();
    let mut counts = BTreeMap::new();
    for generator in minimalize(&leads) {
        *counts.entry(generator.degree()).or_insert(0) += 1;
    }
    counts
}

