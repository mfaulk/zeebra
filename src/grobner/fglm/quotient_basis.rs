//! Classifying an ideal by the dimension of its quotient algebra, and enumerating that algebra's
//! monomial basis.
//!
//! Both questions are answered from the leading monomials of a Gröbner basis alone. The order of
//! the enumerated basis is the source monomial order ascending, which makes index 0 the monomial
//! 1 — every monomial order has 1 below every other monomial — so the coordinate vector of the
//! multiplicative identity is the first unit vector and not something a caller has to look up.
//!
//! See `docs/MILESTONE-FGLM-SOLVING.md` §4 and §5 for the mathematics and the pseudocode.

use std::collections::{HashMap, HashSet};

use crate::{
    grobner::fglm::FglmError, FiniteField, Monomial, MonomialOrder, MultivariatePolynomial,
};

/// What a Gröbner basis says about the dimension of the ideal it generates.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum IdealClass {
    /// `I = R`: the basis contains a nonzero constant, so the system is inconsistent. The
    /// quotient algebra is the zero vector space, of dimension 0.
    ///
    /// Zero-dimensional, and satisfying none of the pure-power conditions below, which is why it
    /// is a case of its own rather than a failure of them.
    Unit,

    /// Proper, with a finite-dimensional quotient algebra.
    ZeroDimensional,

    /// `R/I` is infinite-dimensional. Includes the zero ideal, whose quotient is `R` itself.
    PositiveDimensional,
}

impl IdealClass {
    /// Whether the quotient algebra is finite-dimensional, which is both [`Self::Unit`] and
    /// [`Self::ZeroDimensional`].
    pub fn is_finite_dimensional(&self) -> bool {
        !matches!(self, Self::PositiveDimensional)
    }
}

/// Classify the ideal generated by `basis`, which must be a Gröbner basis under `order`.
///
/// For a proper ideal, `dim R/I` is finite exactly when the leading-term ideal contains a positive
/// power of every variable, and for a Gröbner basis that is a question about leading monomials
/// alone.
///
/// The unit ideal is tested first and separately. It is zero-dimensional with the zero quotient,
/// and it satisfies no pure-power condition, so a classifier that only looked for pure powers
/// would reject the one ideal whose conversion is most trivial.
pub fn classify_ideal<const N: usize, F: FiniteField>(
    basis: &[MultivariatePolynomial<N, F>],
    order: MonomialOrder,
) -> IdealClass {
    if basis.iter().any(|p| p.is_constant() && !p.is_zero()) {
        return IdealClass::Unit;
    }

    // The zero ideal needs no case of its own. Both engines return the empty basis for it, and an
    // empty basis has no leading monomial that is a pure power of anything, so the loop below
    // reports it as positive-dimensional — which is right, since R/{0} = R.
    let leading: Vec<Monomial<N>> = basis.iter().map(|p| p.leading_monomial(order)).collect();
    if (0..N).all(|i| leading.iter().any(|m| is_pure_power_of(m, i))) {
        IdealClass::ZeroDimensional
    } else {
        IdealClass::PositiveDimensional
    }
}

/// Whether `m` is `x_i^d` for some `d > 0`.
///
/// The positive exponent is part of the predicate, not a redundant guard: without it the monomial
/// 1 would answer yes for every variable. `classify_ideal` never asks it about 1, because a basis
/// whose leading monomial is 1 is the unit ideal and returns earlier — but a predicate that is
/// only correct in its caller's context is a trap for the next caller.
fn is_pure_power_of<const N: usize>(m: &Monomial<N>, i: usize) -> bool {
    let exponents = m.exponents();
    exponents[i] > 0
        && exponents
            .iter()
            .enumerate()
            .all(|(j, exponent)| j == i || *exponent == 0)
}

/// The standard monomials of a zero-dimensional ideal: a basis of `R/I` as an `F`-vector space.
///
/// A monomial is standard when no leading monomial of the ideal divides it. Their residue classes
/// are a vector-space basis of the quotient, so the count is the quotient dimension `D` — which is
/// *not* the Krull dimension, and which counts the zeros over the algebraic closure with
/// multiplicity rather than counting distinct points.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct QuotientBasis<const N: usize> {
    /// Ascending under the source order, so `monomials[0]` is 1 whenever the basis is nonempty.
    monomials: Vec<Monomial<N>>,

    /// The inverse of `monomials`, for the coordinate lookups that dominate M17-B and M17-C.
    index: HashMap<Monomial<N>, usize>,

    order: MonomialOrder,
}

impl<const N: usize> QuotientBasis<N> {
    /// Enumerate the standard monomials of the ideal `basis` generates.
    ///
    /// `basis` must be a Gröbner basis under `order`.
    ///
    /// # Errors
    /// [`FglmError::PositiveDimensional`] if the quotient is infinite-dimensional, which is
    /// decided before any enumeration because the enumeration would not terminate.
    /// [`FglmError::QuotientDimensionExceeded`] if more than `max_dimension` standard monomials
    /// are found.
    pub fn new<F: FiniteField>(
        basis: &[MultivariatePolynomial<N, F>],
        order: MonomialOrder,
        max_dimension: usize,
    ) -> Result<Self, FglmError> {
        if !classify_ideal(basis, order).is_finite_dimensional() {
            return Err(FglmError::PositiveDimensional);
        }

        let leading: Vec<Monomial<N>> = basis.iter().map(|p| p.leading_monomial(order)).collect();
        let mut monomials = enumerate_standard(&leading, max_dimension)?;

        // The traversal order is an artifact of the walk. Sorting by the source order makes the
        // index of a monomial a function of the ideal and the order alone, which the coordinate
        // vectors, the multiplication matrices and the reported statistics all depend on.
        monomials.sort_by(|a, b| order.cmp(a, b));

        let index = monomials.iter().enumerate().map(|(i, m)| (*m, i)).collect();

        Ok(Self {
            monomials,
            index,
            order,
        })
    }

    /// `D = dim_F(R/I)`, the number of standard monomials.
    pub fn dimension(&self) -> usize {
        self.monomials.len()
    }

    /// The standard monomials, ascending under [`Self::order`].
    pub fn monomials(&self) -> &[Monomial<N>] {
        &self.monomials
    }

    /// The coordinate index of a standard monomial, or `None` if it is not standard.
    pub fn index_of(&self, monomial: &Monomial<N>) -> Option<usize> {
        self.index.get(monomial).copied()
    }

    /// The order the basis was enumerated and sorted under.
    pub fn order(&self) -> MonomialOrder {
        self.order
    }

    /// Whether the quotient algebra is the zero vector space, i.e. the ideal is the unit ideal.
    pub fn is_empty(&self) -> bool {
        self.monomials.is_empty()
    }
}

/// The monomials divisible by no element of `leading`, by a frontier walk from 1.
///
/// Terminates only when the staircase bounds every variable, so the caller classifies first.
///
/// Correctness rests on the standard monomials being closed downwards: if `m` is standard then so
/// is every divisor of `m`, hence every standard monomial is reachable from 1 by multiplying one
/// variable at a time. Pruning at a non-standard monomial is safe for the same reason read
/// upwards — every multiple of a non-standard monomial is non-standard.
///
/// `max_dimension` is also the backstop against a walk that should not have been started. The
/// pruning is what makes the frontier finite, so a caller that reached here with a
/// positive-dimensional ideal would otherwise loop forever; with the limit it gets an error
/// instead. The classification in `QuotientBasis::new` is the real guard, and this is the one that
/// does not depend on it being right.
fn enumerate_standard<const N: usize>(
    leading: &[Monomial<N>],
    max_dimension: usize,
) -> Result<Vec<Monomial<N>>, FglmError> {
    let mut accepted: Vec<Monomial<N>> = Vec::new();
    let mut seen: HashSet<Monomial<N>> = HashSet::from([Monomial::one()]);
    let mut frontier: Vec<Monomial<N>> = vec![Monomial::one()];

    while let Some(m) = frontier.pop() {
        if leading.iter().any(|lm| m.checked_div(lm).is_some()) {
            continue;
        }
        if accepted.len() == max_dimension {
            return Err(FglmError::QuotientDimensionExceeded {
                limit: max_dimension,
            });
        }
        accepted.push(m);

        for i in 0..N {
            // No overflow is reachable: every exponent of a standard monomial is below its
            // variable's pure power, and a child exceeds that by one at most. `Mul` checks the
            // addition in every build regardless, so a wrapped exponent cannot go unnoticed.
            let child = m * Monomial::univariate(i, 1);
            if seen.insert(child) {
                frontier.push(child);
            }
        }
    }

    Ok(accepted)
}

#[cfg(test)]
mod tests {
    use super::{classify_ideal, is_pure_power_of, IdealClass, QuotientBasis};
    use crate::{
        fields::{PrimeFieldElement64, Zp2147483647},
        grobner::{
            benchmark_systems::{cyclic, katsura, planted},
            f4,
            fglm::FglmError,
        },
        FiniteField, Monomial, MonomialOrder, MultivariatePolynomial, One, Zero,
    };

    type F = Zp2147483647;

    const ORDERS: [MonomialOrder; 3] = [
        MonomialOrder::Lexicographic,
        MonomialOrder::GradedLexicographic,
        MonomialOrder::GradedReverseLexicographic,
    ];

    /// A Gröbner basis of the system the strings generate, under `order`.
    fn basis_of<const N: usize>(
        system: &[&str],
        variables: [&str; N],
        order: MonomialOrder,
    ) -> Vec<MultivariatePolynomial<N, F>> {
        let generators: Vec<MultivariatePolynomial<N, F>> = system
            .iter()
            .map(|s| MultivariatePolynomial::parse(s, variables).unwrap())
            .collect();
        f4(&generators, order).expect("within limits")
    }

    /// The quotient basis of a parsed system, under `order`, with no practical dimension limit.
    fn quotient_basis_of<const N: usize>(
        system: &[&str],
        variables: [&str; N],
        order: MonomialOrder,
    ) -> Result<QuotientBasis<N>, FglmError> {
        QuotientBasis::new(&basis_of(system, variables, order), order, usize::MAX)
    }

    /// An inconsistent system is the unit ideal, whose quotient algebra is zero-dimensional.
    #[test]
    fn test_unit_ideal_is_classified_as_the_unit_ideal() {
        for order in ORDERS {
            let basis = basis_of(&["x", "x - 1"], ["x", "y"], order);
            assert_eq!(classify_ideal(&basis, order), IdealClass::Unit);
            let quotient = QuotientBasis::new(&basis, order, usize::MAX).expect("finite");
            assert_eq!(quotient.dimension(), 0, "{:?}", order);
            assert!(quotient.is_empty());
        }
    }

    /// The zero ideal is positive-dimensional, since R/{0} = R is infinite.
    #[test]
    fn test_zero_ideal_is_positive_dimensional() {
        for order in ORDERS {
            // Both engines return the empty basis for the zero ideal, so this is what they give.
            let empty: Vec<MultivariatePolynomial<2, F>> = Vec::new();
            assert_eq!(
                classify_ideal(&empty, order),
                IdealClass::PositiveDimensional
            );
            assert_eq!(
                QuotientBasis::new(&empty, order, usize::MAX).unwrap_err(),
                FglmError::PositiveDimensional
            );

            // And an all-zero generating set reduces to it.
            let zeros: Vec<MultivariatePolynomial<2, F>> = vec![MultivariatePolynomial::zero()];
            let basis = f4(&zeros, order).expect("within limits");
            assert_eq!(
                classify_ideal(&basis, order),
                IdealClass::PositiveDimensional
            );
        }
    }

    /// A single univariate polynomial of degree d has quotient dimension d.
    #[test]
    fn test_univariate_quotient_dimension_is_the_degree() {
        for order in ORDERS {
            for degree in 1..=6u32 {
                let generator: MultivariatePolynomial<1, F> = MultivariatePolynomial::new(&[
                    (Monomial::univariate(0, degree), F::one()),
                    (Monomial::one(), F::zero() - F::one()),
                ]);
                let basis = f4(&[generator], order).expect("within limits");
                let quotient = QuotientBasis::new(&basis, order, usize::MAX).expect("finite");
                assert_eq!(
                    quotient.dimension(),
                    degree as usize,
                    "x^{} - 1 under {:?}",
                    degree,
                    order
                );
            }
        }
    }

    /// `<x^a, y^b>` has quotient dimension a*b, the size of the staircase's rectangle.
    #[test]
    fn test_monomial_ideal_quotient_dimension_is_the_product() {
        for order in ORDERS {
            for a in 1..=4u32 {
                for b in 1..=4u32 {
                    let x_a = format!("x^{}", a);
                    let y_b = format!("y^{}", b);
                    let quotient =
                        quotient_basis_of(&[&x_a, &y_b], ["x", "y"], order).expect("finite");
                    assert_eq!(
                        quotient.dimension(),
                        (a * b) as usize,
                        "<x^{}, y^{}> under {:?}",
                        a,
                        b,
                        order
                    );
                }
            }
        }
    }

    /// `<x^2, y^2>` has exactly the standard monomials 1, x, y, xy.
    ///
    /// The nonradical case the milestone turns on: one distinct zero over the algebraic closure
    /// and a quotient algebra of dimension four. Anything that inferred the point count from the
    /// dimension, or the dimension from the point count, would be wrong here.
    #[test]
    fn test_nonradical_monomial_ideal_has_the_expected_standard_monomials() {
        for order in ORDERS {
            let quotient = quotient_basis_of(&["x^2", "y^2"], ["x", "y"], order).expect("finite");
            let expected = [
                Monomial::<2>::one(),
                Monomial::new(&[1, 0]),
                Monomial::new(&[0, 1]),
                Monomial::new(&[1, 1]),
            ];
            let found: std::collections::HashSet<_> =
                quotient.monomials().iter().copied().collect();
            assert_eq!(
                found,
                expected.into_iter().collect(),
                "<x^2, y^2> under {:?}",
                order
            );
        }
    }

    /// `<(x-1)^2, y-x>` keeps the multiplicity: dimension two, one distinct point.
    #[test]
    fn test_nonradical_ideal_keeps_its_multiplicity() {
        for order in ORDERS {
            let quotient =
                quotient_basis_of(&["x^2 - 2*x + 1", "y - x"], ["x", "y"], order).expect("finite");
            assert_eq!(quotient.dimension(), 2, "{:?}", order);
        }
    }

    /// `<x^2 - y, y^3 - 1>` is zero-dimensional of dimension six.
    #[test]
    fn test_a_mixed_system_has_the_expected_dimension() {
        for order in ORDERS {
            let quotient =
                quotient_basis_of(&["x^2 - y", "y^3 - 1"], ["x", "y"], order).expect("finite");
            assert_eq!(quotient.dimension(), 6, "{:?}", order);
        }
    }

    /// `<xy - 1>` is positive-dimensional: a curve, not a finite set of points.
    #[test]
    fn test_a_curve_is_positive_dimensional() {
        for order in ORDERS {
            let basis = basis_of(&["x*y - 1"], ["x", "y"], order);
            assert_eq!(
                classify_ideal(&basis, order),
                IdealClass::PositiveDimensional
            );
            assert_eq!(
                QuotientBasis::new(&basis, order, usize::MAX).unwrap_err(),
                FglmError::PositiveDimensional
            );
        }
    }

    /// Cyclic-4 is positive-dimensional and must be rejected rather than enumerated.
    ///
    /// The regression case for the whole milestone: it is square, it is a standard benchmark, and
    /// enumerating its standard monomials would not terminate.
    #[test]
    fn test_cyclic_4_is_rejected() {
        for order in ORDERS {
            let basis = f4(&cyclic::<4, F>(), order).expect("within limits");
            assert_eq!(
                classify_ideal(&basis, order),
                IdealClass::PositiveDimensional,
                "{:?}",
                order
            );
            assert_eq!(
                QuotientBasis::new(&basis, order, usize::MAX).unwrap_err(),
                FglmError::PositiveDimensional
            );
        }
    }

    /// The quotient dimension does not depend on the monomial order, though the monomials do.
    ///
    /// `D = dim_F(R/I)` is an invariant of the ideal. The standard monomial *sets* under lex and
    /// grevlex are usually different, so agreement of the counts is a real cross-check on the
    /// enumeration rather than a restatement of it.
    #[test]
    fn test_quotient_dimension_is_independent_of_the_order() {
        let systems: [&[&str]; 5] = [
            &["x^2", "y^2"],
            &["x^2 - y", "y^3 - 1"],
            &["x + y", "x*y - 1"],
            &["x^3 - 1", "y - x^2"],
            &["x^2 + y^2 - 1", "x - y"],
        ];
        for system in systems {
            let dimensions: Vec<usize> = ORDERS
                .iter()
                .map(|order| {
                    quotient_basis_of(system, ["x", "y"], *order)
                        .expect("finite")
                        .dimension()
                })
                .collect();
            assert!(
                dimensions.windows(2).all(|w| w[0] == w[1]),
                "{:?} gave dimensions {:?} across {:?}",
                system,
                dimensions,
                ORDERS
            );
        }
    }

    /// The standard monomials are closed downwards: every divisor of one is also one.
    ///
    /// The property the frontier walk's correctness rests on, so it is checked rather than
    /// assumed. A walk that pruned too eagerly would drop a standard monomial whose divisors it
    /// kept.
    #[test]
    fn test_standard_monomials_are_closed_downwards() {
        let systems: [&[&str]; 4] = [
            &["x^2", "y^3"],
            &["x^2 - y", "y^3 - 1"],
            &["x^4 - 1", "y^2 - x"],
            &["x + y", "x*y - 1"],
        ];
        for order in ORDERS {
            for system in systems {
                let quotient = quotient_basis_of(system, ["x", "y"], order).expect("finite");
                for m in quotient.monomials() {
                    for i in 0..2 {
                        if m.exponents()[i] == 0 {
                            continue;
                        }
                        let mut exponents = [m.exponents()[0], m.exponents()[1]];
                        exponents[i] -= 1;
                        let divisor = Monomial::new(&exponents);
                        assert!(
                            quotient.index_of(&divisor).is_some(),
                            "{} is standard but its divisor {} is not, in {:?} under {:?}",
                            m,
                            divisor,
                            system,
                            order
                        );
                    }
                }
            }
        }
    }

    /// A monomial is a pure power of exactly the variable it uses, and 1 is a pure power of none.
    ///
    /// Tested directly because every call in `classify_ideal` is shielded by the unit-ideal check,
    /// so the `1` case is unreachable from there and would otherwise go unexercised.
    #[test]
    fn test_pure_power_recognizes_only_pure_powers() {
        assert!(is_pure_power_of(&Monomial::<3>::new(&[2, 0, 0]), 0));
        assert!(is_pure_power_of(&Monomial::<3>::new(&[0, 1, 0]), 1));
        assert!(is_pure_power_of(&Monomial::<3>::new(&[0, 0, 5]), 2));

        // A pure power of x_0 is not one of x_1.
        assert!(!is_pure_power_of(&Monomial::<3>::new(&[2, 0, 0]), 1));
        // Mixed monomials are pure powers of nothing.
        assert!(!is_pure_power_of(&Monomial::<3>::new(&[1, 1, 0]), 0));
        assert!(!is_pure_power_of(&Monomial::<3>::new(&[1, 1, 0]), 1));
        // 1 is a pure power of no variable, since the exponent must be positive.
        for i in 0..3 {
            assert!(
                !is_pure_power_of(&Monomial::<3>::one(), i),
                "1 was taken for a pure power of x_{}",
                i
            );
        }
    }

    /// The monomials are strictly ascending under the order they were built with.
    ///
    /// The documented contract, and the reason the coordinate indices are a function of the ideal
    /// and the order alone. The frontier walk's own traversal order is not a monomial order, so
    /// this is a property of the sort and not of the walk — and it does not follow from index 0
    /// being 1, which the walk gives for free.
    #[test]
    fn test_the_monomials_are_sorted_by_the_order() {
        let systems: [&[&str]; 3] = [
            &["x^3", "y^4"],
            &["x^2 - y", "y^3 - 1"],
            &["x^4 - 1", "y^2 - x"],
        ];
        for order in ORDERS {
            for system in systems {
                let quotient = quotient_basis_of(system, ["x", "y"], order).expect("finite");
                let monomials = quotient.monomials();
                for pair in monomials.windows(2) {
                    assert_eq!(
                        order.cmp(&pair[0], &pair[1]),
                        std::cmp::Ordering::Less,
                        "{} and {} are out of order in {:?} under {:?}",
                        pair[0],
                        pair[1],
                        system,
                        order
                    );
                }
            }
        }
    }

    /// Index 0 is the monomial 1, and `index_of` inverts `monomials` exactly.
    ///
    /// The identity's coordinate vector is the first unit vector because of this, which M17-B
    /// relies on.
    #[test]
    fn test_index_inverts_the_monomial_list() {
        for order in ORDERS {
            let quotient =
                quotient_basis_of(&["x^3 - y", "y^2 - 1"], ["x", "y"], order).expect("finite");
            assert_eq!(quotient.monomials()[0], Monomial::one(), "{:?}", order);
            for (i, m) in quotient.monomials().iter().enumerate() {
                assert_eq!(quotient.index_of(m), Some(i));
            }
            // A monomial above the staircase is not standard.
            assert_eq!(quotient.index_of(&Monomial::new(&[9, 9])), None);
        }
    }

    /// Permuting the generators gives an identical quotient basis, monomials and indices alike.
    #[test]
    fn test_the_quotient_basis_does_not_depend_on_generator_order() {
        for order in ORDERS {
            let forwards =
                quotient_basis_of(&["x^2 - y", "y^3 - 1"], ["x", "y"], order).expect("finite");
            let backwards =
                quotient_basis_of(&["y^3 - 1", "x^2 - y"], ["x", "y"], order).expect("finite");
            assert_eq!(forwards, backwards, "{:?}", order);
        }
    }

    /// A dimension limit below the true dimension is a structured error, not a truncated basis.
    #[test]
    fn test_the_dimension_limit_is_enforced() {
        let order = MonomialOrder::GradedReverseLexicographic;
        let basis = basis_of(&["x^2", "y^2"], ["x", "y"], order);
        // The true dimension is four.
        for limit in 0..4 {
            assert_eq!(
                QuotientBasis::new(&basis, order, limit).unwrap_err(),
                FglmError::QuotientDimensionExceeded { limit },
                "a limit of {} should have been exceeded",
                limit
            );
        }
        assert_eq!(
            QuotientBasis::new(&basis, order, 4)
                .expect("exactly at the limit")
                .dimension(),
            4
        );
    }

    /// `x^2 + 1` over GF(3) is zero-dimensional of dimension two, with no base-field root.
    ///
    /// The quotient dimension counts zeros over the algebraic closure, so it says nothing about
    /// how many points lie in the base field. Here it is two and there are none.
    #[test]
    fn test_a_system_with_no_base_field_solution_is_still_zero_dimensional() {
        type Gf3 = PrimeFieldElement64<3>;
        let order = MonomialOrder::Lexicographic;
        let generator: MultivariatePolynomial<1, Gf3> = MultivariatePolynomial::new(&[
            (Monomial::univariate(0, 2), Gf3::one()),
            (Monomial::one(), Gf3::one()),
        ]);
        let basis = f4(&[generator], order).expect("within limits");
        assert_eq!(classify_ideal(&basis, order), IdealClass::ZeroDimensional);
        assert_eq!(
            QuotientBasis::new(&basis, order, usize::MAX)
                .expect("finite")
                .dimension(),
            2
        );
    }

    /// The benchmark corpus has the quotient dimensions the M17-0 baseline measured.
    ///
    /// Katsura-n has D = 2^(n-1), the cyclic family 6 and 70 at these sizes, and the planted
    /// family 4^(N/2) — each pair of variables contributing its four solutions. These are the
    /// figures `docs/MILESTONE-FGLM-SOLVING.md` §10 reports, so the table is now asserted rather
    /// than only recorded.
    #[test]
    fn test_the_benchmark_corpus_has_its_recorded_dimensions() {
        /// The quotient dimension of a system's grevlex basis. A function rather than a closure
        /// because each system has a different `N`.
        fn dimension_of<const N: usize>(system: &[MultivariatePolynomial<N, F>]) -> usize {
            let order = MonomialOrder::GradedReverseLexicographic;
            let basis = f4(system, order).expect("within limits");
            QuotientBasis::new(&basis, order, usize::MAX)
                .expect("finite")
                .dimension()
        }

        assert_eq!(dimension_of(&cyclic::<3, F>()), 6);
        assert_eq!(dimension_of(&cyclic::<5, F>()), 70);
        assert_eq!(dimension_of(&katsura::<3, F>()), 4);
        assert_eq!(dimension_of(&katsura::<4, F>()), 8);
        assert_eq!(dimension_of(&katsura::<5, F>()), 16);

        let point: Vec<F> = [3u64, 5, 7, 11].iter().map(|v| F::new(*v)).collect();
        assert_eq!(dimension_of(&planted::<4, F>(&point)), 16);
    }
}
