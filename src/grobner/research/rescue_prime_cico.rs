//! Rescue-Prime CICO, with the inverse S-box written as `y^α = x`.
//!
//! #203's second technical gap. A Rescue round applies `x^{1/α}` to every word, and `1/α` means
//! `α^{-1} mod (p − 1)` — for `α = 3` and `p = 2^64 − 59` that is `12297829382473034371`, so the
//! polynomial `x ↦ x^{α^{-1}}` has degree about `2^64/3` and writing it down is not an option.
//!
//! # The relation is written backwards, deliberately
//!
//! `y = x^{1/α}` and `y^α = x` have the same solutions, because `x ↦ x^α` is a bijection when
//! `gcd(α, p − 1) = 1` — which [`RescuePrime::new`] checks. The second form is degree `α`. So the
//! model carries a variable for every **inverse** S-box output and states its defining relation in
//! the cheap direction. That is the standard trick, and it is recorded here rather than left
//! implicit because it changes the generator set: the ideal is generated by `N·t` cubics and one
//! linear form, not by anything of degree `α^{-1}`.
//!
//! [`RescuePrime::new`]: super::RescuePrime::new
//!
//! # Why the variables are the inverse S-box outputs and not the round inputs
//!
//! Putting variables on the round *inputs* `u_r` needs `M^{-1}` to express the inverse S-box
//! output, since `u_{r+1} = M·z_r + c_{2r+1}` has to be read backwards. Putting them on the
//! inverse S-box outputs `z_r` does not: `u_r` is then an **affine** expression in `z_{r−1}`, the
//! round relation `z_r^α = M·u_r^α + c_{2r}` is degree `α` in each, and no matrix inversion enters
//! the construction at all. One fewer transcribed quantity is one fewer thing that can be wrong.
//!
//! # `t = 3` is underdetermined by one and `t = 2` is square
//!
//! The objective is CICO(1) on the **trailing** word — `Perm(X_1…X_{t−1}, 0) = (Y_1…Y_{t−1}, 0)`,
//! as the reference's verifier writes it. `docs/research/structure-experiments.md` §1's bookkeeping
//! gives `N − E = t − 2k = t − 2`: zero for `EASY2`, `MEDIUM` and `HARD2`, and **one** for `EASY1`
//! and `HARD1`. The two `t = 3` instances therefore have a one-dimensional solution variety and
//! need a slice or a planted coordinate before any zero-dimensional solver will accept them —
//! and `docs/research/poseidon.md` §4 records M21-E's rule that an `EmptySlice` is not evidence
//! about the system.

use crate::{
    grobner::research::rescue_prime::{RescuePrime, RescuePrimeError},
    FiniteField, KnownOrder, Monomial, MultivariatePolynomial,
};

/// A Rescue-Prime CICO instance.
#[derive(Clone, Debug)]
pub struct RescuePrimeCico<F: KnownOrder> {
    /// The permutation.
    pub rescue: RescuePrime<F>,
}

impl<F: KnownOrder> RescuePrimeCico<F> {
    /// A CICO instance over this permutation.
    pub fn new(rescue: RescuePrime<F>) -> Self {
        Self { rescue }
    }

    /// The number of variables: `t − 1` free input words plus `t` per round.
    pub fn variables(&self) -> usize {
        let t = self.rescue.parameters.t();
        (t - 1) + self.rescue.parameters.rounds * t
    }

    /// The number of generators: `t` cubics per round plus one linear output constraint.
    pub fn equations(&self) -> usize {
        self.rescue.parameters.rounds * self.rescue.parameters.t() + 1
    }

    /// `N − E`, which is `t − 2k = t − 2` here.
    ///
    /// Positive means the system is underdetermined and a zero-dimensional solver needs a slice.
    pub fn excess_variables(&self) -> usize {
        self.variables() - self.equations()
    }

    /// The generator degrees, in the order [`Self::system`] emits them.
    pub fn generator_degrees(&self) -> Vec<u64> {
        let mut degrees = vec![u64::from(self.rescue.parameters.alpha); self.equations() - 1];
        degrees.push(1);
        degrees
    }

    /// The polynomial system, at a compile-time dimension.
    ///
    /// Variable order, which Zeebra's degrevlex induces from the indices: the `t − 1` free input
    /// words first, then `z_0, z_1, …, z_{N−1}` in round order, `t` words each. Early-round
    /// variables are therefore larger, as in the Six Worlds `o1` ordering
    /// [`AnemoiCico`](super::AnemoiCico) follows.
    ///
    /// # Errors
    /// [`RescuePrimeError::WrongDimension`] if `N` is not [`Self::variables`].
    pub fn system<const N: usize>(
        &self,
    ) -> Result<Vec<MultivariatePolynomial<N, F>>, RescuePrimeError> {
        let needed = self.variables();
        if N != needed {
            return Err(RescuePrimeError::WrongDimension {
                needed,
                requested: N,
            });
        }
        let t = self.rescue.parameters.t();
        let rounds = self.rescue.parameters.rounds;
        let alpha = self.rescue.parameters.alpha;
        let z = |round: usize, word: usize| -> MultivariatePolynomial<N, F> {
            variable((t - 1) + round * t + word)
        };
        // `M·z_{round-1} + c_{2*round-1}`, the round's input, affine in the previous round's
        // variables; at round zero it is the CICO input `(X_1..X_{t-1}, 0)`.
        let input = |round: usize, word: usize| -> MultivariatePolynomial<N, F> {
            if round == 0 {
                if word + 1 == t {
                    MultivariatePolynomial::zero()
                } else {
                    variable(word)
                }
            } else {
                let mut accumulator = constant(self.rescue.round_constants[2 * round - 1][word]);
                for column in 0..t {
                    accumulator += z(round - 1, column).scale(&self.rescue.mds[word][column]);
                }
                accumulator
            }
        };

        let mut equations = Vec::with_capacity(self.equations());
        for round in 0..rounds {
            for word in 0..t {
                // z_round[word]^alpha = sum_col M[word][col] * input(round, col)^alpha + c_{2r}
                let mut right = constant(self.rescue.round_constants[2 * round][word]);
                for column in 0..t {
                    right +=
                        power(&input(round, column), alpha).scale(&self.rescue.mds[word][column]);
                }
                equations.push(power(&z(round, word), alpha) - right);
            }
        }
        // The CICO condition on the output's trailing word, which is affine in `z_{N-1}`.
        equations.push(input(rounds, t - 1));
        Ok(equations)
    }

    /// The assignment a trace of the permutation gives this model's variables.
    ///
    /// `z_r` is the inverse S-box's output in round `r`, which is trace index `4r + 3`. Returns
    /// `None` if `N` is not [`Self::variables`] or `free` is not `t − 1` words.
    pub fn assignment<const N: usize>(&self, free: &[F]) -> Option<[F; N]> {
        let t = self.rescue.parameters.t();
        if N != self.variables() || free.len() + 1 != t {
            return None;
        }
        let mut input = free.to_vec();
        input.push(F::zero());
        let trace = self.rescue.trace(&input);
        let mut point = [F::zero(); N];
        point[..t - 1].copy_from_slice(free);
        for round in 0..self.rescue.parameters.rounds {
            for word in 0..t {
                point[(t - 1) + round * t + word] = trace[4 * round + 3][word];
            }
        }
        Some(point)
    }

    /// Whether `(free…, 0)` solves this instance, checked through the permutation.
    pub fn is_solution(&self, free: &[F]) -> bool {
        self.rescue.is_cico_solution(free)
    }
}

/// Whether every generator of `system` vanishes at the trace of `(free…, 0)`.
///
/// Returns the indices that did **not** vanish.
///
/// # An arbitrary input is expected to fail on the last generator
///
/// The `N·t` round relations hold at *any* input; the final linear generator is the CICO objective
/// and holds only at a solution. So an empty return means the input solves the instance, and a
/// return of exactly the last index means the model is faithful and the input is not a solution.
/// Only a failure at an earlier index is evidence of an unfaithful model.
pub fn verify_against_rescue_prime_trace<const N: usize, F: KnownOrder>(
    instance: &RescuePrimeCico<F>,
    system: &[MultivariatePolynomial<N, F>],
    free: &[F],
) -> Vec<usize> {
    let Some(point) = instance.assignment::<N>(free) else {
        return (0..system.len()).collect();
    };
    system
        .iter()
        .enumerate()
        .filter(|(_, p)| !p.eval(&point).is_zero())
        .map(|(i, _)| i)
        .collect()
}

/// Something to do with a Rescue-Prime CICO system once its dimension is known.
pub trait RescuePrimeCicoVisitor<F: KnownOrder> {
    /// What the visit produces. Must not mention the dimension.
    type Output;

    /// Called once, with the system at its own dimension.
    fn visit<const N: usize>(self, system: &[MultivariatePolynomial<N, F>]) -> Self::Output;
}

/// Build `instance`'s system and hand it to `visitor` at its own dimension.
///
/// # Errors
/// [`RescuePrimeError::WrongDimension`] if the instance's variable count has no compiled dimension.
pub fn dispatch_rescue_prime_cico<F: KnownOrder, V: RescuePrimeCicoVisitor<F>>(
    instance: &RescuePrimeCico<F>,
    visitor: V,
) -> Result<V::Output, RescuePrimeError> {
    let variables = instance.variables();

    // `t = 2` at N = 1..8 gives 3, 5, 7, 9, 11, 13, 15, 17; `t = 3` at N = 1..5 gives 5, 8, 11,
    // 14, 17. A spare `N` monomorphizes the whole pipeline again.
    macro_rules! dispatch {
        ($($n:literal),+ $(,)?) => {
            match variables {
                $($n => Ok(visitor.visit(&instance.system::<$n>()?)),)+
                variables => Err(RescuePrimeError::WrongDimension {
                    needed: variables,
                    requested: 0,
                }),
            }
        };
    }
    dispatch!(3, 5, 7, 8, 9, 11, 13, 14, 15, 17)
}

/// The constant polynomial `c`.
fn constant<const N: usize, F: FiniteField>(c: F) -> MultivariatePolynomial<N, F> {
    MultivariatePolynomial::new(&[(Monomial::one(), c)])
}

/// The polynomial `x_index`.
fn variable<const N: usize, F: FiniteField>(index: usize) -> MultivariatePolynomial<N, F> {
    MultivariatePolynomial::new(&[(Monomial::univariate(index, 1), F::one())])
}

/// `p^alpha`, by repeated multiplication; `alpha` is 3 in every bounty instance.
fn power<const N: usize, F: FiniteField>(
    p: &MultivariatePolynomial<N, F>,
    alpha: u32,
) -> MultivariatePolynomial<N, F> {
    let mut accumulator = MultivariatePolynomial::one();
    for _ in 0..alpha {
        accumulator *= p.clone();
    }
    accumulator
}

#[cfg(test)]
mod tests {
    use super::{verify_against_rescue_prime_trace, RescuePrimeCico};
    use crate::{
        fields::Zp18446744073709551557,
        grobner::research::rescue_prime::{
            BountyInstance, RescuePrime, RescuePrimeError, RescuePrimeParameters,
        },
        identities::Zero,
        FiniteField, MonomialOrder,
    };

    type F = Zp18446744073709551557;

    fn instance(bounty: BountyInstance, rounds: usize) -> RescuePrimeCico<F> {
        RescuePrimeCico::new(
            RescuePrime::new(RescuePrimeParameters::reduced(bounty, rounds)).expect("builds"),
        )
    }

    /// The `y^α = x` relations reproduce the permutation's own arithmetic at an arbitrary input,
    /// and the final generator evaluates to the permutation's trailing output word.
    ///
    /// #203's assertion (b), in the form that pins the model at every input rather than only where
    /// it vanishes. The round relations are trace identities; the last generator is the objective.
    #[test]
    fn test_the_round_relations_reproduce_the_permutation() {
        macro_rules! check {
            ($bounty:expr, $rounds:literal, $dimension:literal) => {{
                let cico = instance($bounty, $rounds);
                let t = cico.rescue.parameters.t();
                let system = cico.system::<$dimension>().expect("right dimension");
                assert_eq!(system.len(), cico.equations());
                for seed in 1u64..5 {
                    let free: Vec<F> = (0..t - 1)
                        .map(|i| F::new(seed * 7_919 + i as u64 * 101 + 3))
                        .collect();
                    let point = cico.assignment::<$dimension>(&free).expect("assigns");
                    for (index, generator) in system[..system.len() - 1].iter().enumerate() {
                        assert!(
                            generator.eval(&point).is_zero(),
                            "{}, N = {}, seed {}: round relation {} does not hold",
                            $bounty,
                            $rounds,
                            seed,
                            index
                        );
                    }
                    let mut input = free.clone();
                    input.push(F::zero());
                    let output = cico.rescue.permutation(&input);
                    assert_eq!(
                        system[system.len() - 1].eval(&point),
                        output[t - 1],
                        "{}, N = {}, seed {}: the objective is not the trailing word",
                        $bounty,
                        $rounds,
                        seed
                    );
                }
            }};
        }
        // Both widths, and the specified round count of each `t = 3` instance.
        check!(BountyInstance::Easy1, 1, 5);
        check!(BountyInstance::Easy1, 2, 8);
        check!(BountyInstance::Easy1, 4, 14);
        check!(BountyInstance::Hard1, 5, 17);
        check!(BountyInstance::Easy2, 1, 3);
        check!(BountyInstance::Easy2, 3, 7);
        check!(BountyInstance::Medium, 7, 15);
        check!(BountyInstance::Hard2, 8, 17);
    }

    /// `verify_against_rescue_prime_trace` fails on exactly the objective generator at a
    /// non-solution, which is the model being faithful rather than the model being wrong.
    #[test]
    fn test_only_the_objective_fails_at_a_non_solution() {
        let cico = instance(BountyInstance::Easy2, 3);
        let system = cico.system::<7>().expect("right dimension");
        let free = [F::new(12_345)];
        assert!(!cico.is_solution(&free));
        assert_eq!(
            verify_against_rescue_prime_trace(&cico, &system, &free),
            vec![system.len() - 1]
        );
    }

    /// The dimension bookkeeping is `N − E = t − 2`: square at `t = 2`, underdetermined by one at
    /// `t = 3`.
    ///
    /// The trap `docs/research/degree-profiles.md` §4 names — two instances compared at different
    /// algebraic dimensions — made explicit so a comparison can be made at matched dimension.
    #[test]
    fn test_the_excess_variable_count_is_t_minus_two() {
        for bounty in [BountyInstance::Easy1, BountyInstance::Hard1] {
            for rounds in 1..=bounty.rounds() {
                assert_eq!(instance(bounty, rounds).excess_variables(), 1, "{bounty}");
            }
        }
        for bounty in [
            BountyInstance::Easy2,
            BountyInstance::Medium,
            BountyInstance::Hard2,
        ] {
            for rounds in 1..=bounty.rounds() {
                assert_eq!(instance(bounty, rounds).excess_variables(), 0, "{bounty}");
            }
        }
    }

    /// The stated generator degrees match the built system: `N·t` cubics then one linear form.
    #[test]
    fn test_the_stated_degrees_match_the_built_system() {
        let cico = instance(BountyInstance::Easy2, 3);
        let system = cico.system::<7>().expect("right dimension");
        let degrees: Vec<u64> = system
            .iter()
            .map(|p| {
                p.leading_monomial(MonomialOrder::GradedReverseLexicographic)
                    .degree()
            })
            .collect();
        assert_eq!(degrees, cico.generator_degrees());
        assert_eq!(degrees, vec![3, 3, 3, 3, 3, 3, 1]);
    }

    /// A dimension that is not the model's variable count is refused rather than padded.
    #[test]
    fn test_the_dimension_is_enforced() {
        let cico = instance(BountyInstance::Easy2, 3);
        assert_eq!(
            cico.system::<8>().err(),
            Some(RescuePrimeError::WrongDimension {
                needed: 7,
                requested: 8
            })
        );
        // A free-word list of the wrong width is refused too.
        assert!(cico.assignment::<7>(&[F::new(1), F::new(2)]).is_none());
    }
}
